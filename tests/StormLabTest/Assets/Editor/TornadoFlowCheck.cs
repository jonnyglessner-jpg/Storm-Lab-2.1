// Does the tornado flow, or does it loop? The game holds a storm moment and advances the wall clock frame by frame, as a
// player sees it; this does the same on a close rope, cone and wedge (the perf check's views) for 10 s at 30 fps and
// measures how much each frame differs from the one before (mean per-pixel change, 0-255). The spin, the rising dust and
// the sway change the image steadily, so a smooth flow has a flat trace; a texture that winds up and snaps back (user,
// 2026-10-30: the debris cloud and part of the funnel distort, then the animation hard-resets, on a loop) shows as
// spikes several times the median. PASS when no frame changes more than 2.5x the median in any view.
//   StormLab > Tornado Flow Check
// Batch: -executeMethod TornadoFlowCheck.RunFromCommandLine [-slFlowSeconds s] [-slFlowW w -slFlowH h] [-slFlowTag name]
// [-slFlowStrip s] (never with -nographics). Report validation/reports/TornadoFlowCheck.md (TornadoFlowCheck_<tag>.md with
// a tag), the trace of every view as CSV beside it, and the frames round each view's worst spike in
// Screenshots/flow_*.png. -slFlowStrip s also keeps a frame every s seconds (flow_<view>_s<n>.png), to judge how the
// dust moves over seconds (turning against rising) rather than frame to frame.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using StormLab;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using Debug = UnityEngine.Debug;
using Object = UnityEngine.Object;

public static class TornadoFlowCheck
{
    static string ShotDir => Path.Combine(StormLabTestKit.ProjectDir, "Screenshots");
    static int W = 1720, H = 720;
    static float seconds = 10f, strip = 0f;
    const float Fps = 30f;
    const double SpikeRatio = 2.5;

    [MenuItem("StormLab/Tornado Flow Check")]
    public static void RunMenu() => Run(null);

    public static void RunFromCommandLine()
    {
        var a = System.Environment.GetCommandLineArgs();
        string Arg(string k) { int i = Array.IndexOf(a, k); return i >= 0 && i + 1 < a.Length ? a[i + 1] : null; }
        if (int.TryParse(Arg("-slFlowW"), out var w)) W = w;
        if (int.TryParse(Arg("-slFlowH"), out var h)) H = h;
        if (float.TryParse(Arg("-slFlowSeconds"), out var s)) seconds = s;
        if (float.TryParse(Arg("-slFlowStrip"), out var st)) strip = st;
        bool ok;
        try { ok = Run(Arg("-slFlowTag")); }
        catch (Exception e) { Debug.LogException(e); ok = false; }
        // leave the editor on the test map, not this run's empty scene (the editor reopens on the last scene it had)
        try { EditorSceneManager.OpenScene("Assets/Scenes/TestMap.unity", OpenSceneMode.Single); } catch (Exception e) { Debug.LogWarning(e.Message); }
        EditorApplication.Exit(ok ? 0 : 1);
    }

    static StormRenderer storm; static Camera cam;

    static Vector3 Bearing(float deg) { float r = deg * Mathf.Deg2Rad; return new Vector3(Mathf.Sin(r), 0f, Mathf.Cos(r)); }

    static bool Run(string tag)
    {
        StormLabTestKit.EnsurePipeline();
        EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        ShaderUtil.allowAsyncCompilation = false;
        var camGo = new GameObject("Main Camera") { tag = "MainCamera" };
        cam = camGo.AddComponent<Camera>();
        cam.nearClipPlane = 0.3f; cam.farClipPlane = 400000f;
        StormLabTestKit.SetupCamera(camGo);
        // the game's settings (the renderer's defaults), a late-afternoon sun, as the perf check
        storm = new GameObject("Storm").AddComponent<StormRenderer>();
        storm.playing = false;
        storm.sunSource = SunSource.Fixed; storm.sunAzimuth = 255f; storm.sunElevation = 25f;
        storm.preset = "plains"; storm.varied = true; storm.seed = 42; storm.Replan();
        var P = storm.Plan;

        var rep = new StringBuilder("# Tornado flow\n\n");
        rep.AppendLine($"Generated by `TornadoFlowCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}, {SystemInfo.graphicsDeviceName}, {W} x {H}, tier {storm.performance}. " +
                       $"Each view holds its storm moment and advances the wall clock {seconds:0} s at {Fps:0} fps; the trace is the mean per-pixel " +
                       $"change (0-255) from one frame to the next. PASS: no frame changes more than {SpikeRatio:0.0}x the view's median.").AppendLine();
        rep.AppendLine("| view | median change | worst change | at clock | worst / median | spikes over the bar | |");
        rep.AppendLine("| --- | --- | --- | --- | --- | --- | --- |");

        TornadoCharacter[] natural = storm.Tornadoes;
        bool Forced(FunnelShape shape, double w, int ef, float km, float up)
        {
            storm.Replan();
            var forced = StormTornadoes.Forced(P, ClimoRegion.Plains, 0, shape, w, ef);
            if (forced == null) return false;
            if (shape == FunnelShape.Wedge)
            {
                double k = w / 2000.0 / forced.groundKm;
                forced.groundKm *= k; forced.topKm *= k; forced.rcKm = Math.Min(forced.rcKm * k, 0.6); forced.widthM = w;
                for (int i = 0; i < forced.phases.Length; i++) { var p = forced.phases[i]; p.groundKm *= k; p.topKm *= k; forced.phases[i] = p; }
            }
            var chars = storm.Tornadoes; chars[0] = forced; storm.Tornadoes = chars;
            float T = (float)(forced.formMin + (shape == FunnelShape.Wedge ? 0.55 : 0.4) * forced.LifeMin);
            storm.Spin.Reset();
            storm.StepTo(T, 100f, true); StormLabTestKit.Sync();
            var g = storm.TornadoGroundWorld; g.y = 0f;
            float zb = (float)(P.zb - StormDesign.CLOUD_BASE_LIFT_KM);
            float D = storm.Frame.param[14 * 4] * 1000f + km * 1000f;
            var from = g + Bearing(140f) * D + Vector3.up * up;
            var at = up > 10f ? g + Vector3.up * 30f : g + Vector3.up * zb * 400f;
            cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(at - from, Vector3.up));
            cam.fieldOfView = 60f;
            return true;
        }
        var views = new (string name, Func<bool> place)[]
        {
            ("rope_0.4km", () => Forced(FunnelShape.Rope, 90, 1, 0.4f, 2f)),
            ("cone_0.4km", () => Forced(FunnelShape.Cone, 350, 2, 0.4f, 2f)),
            ("wedge_1.5km", () => Forced(FunnelShape.Wedge, 1800, 4, 1.5f, 2f)),
        };

        bool ok = true;
        int n = (int)(seconds * Fps);
        string suffix = string.IsNullOrEmpty(tag) ? "" : "_" + tag;
        Directory.CreateDirectory(ShotDir);
        string repDir = Path.Combine(StormLabTestKit.RepoRoot, "validation", "reports");
        Directory.CreateDirectory(repDir);
        foreach (var v in views)
        {
            storm.Tornadoes = natural;
            if (!v.place()) { rep.AppendLine($"| {v.name} | FAIL: could not place | | | | | |"); ok = false; continue; }
            double T = storm.StormTime; float clock = 100f;
            storm.ResetHistory(cam);
            // the temporal resolve settles first (the game has been running)
            for (int f = 0; f < 16; f++)
            {
                clock += 1f / Fps; storm.StepTo(T, clock);
                using (var cmd = new UnityEngine.Rendering.CommandBuffer()) { storm.RecordMarch(cmd, cam, null, W, H, false, out _); Graphics.ExecuteCommandBuffer(cmd); }
            }
            var trace = new List<(float clock, double change)>();
            byte[] prev = null;
            var all = new List<byte[]>();   // every frame as PNG, for the pictures round the worst change
            for (int f = 0; f < n; f++)
            {
                clock += 1f / Fps; storm.StepTo(T, clock);
                RenderTexture rt;
                using (var cmd = new UnityEngine.Rendering.CommandBuffer()) { rt = storm.RecordMarch(cmd, cam, null, W, H, false, out _); Graphics.ExecuteCommandBuffer(cmd); }
                var tex = Grab(rt);
                var lum = tex.GetPixels32().Select(c => (byte)((c.r + c.g + c.b) / 3)).ToArray();
                all.Add(tex.EncodeToPNG()); Object.DestroyImmediate(tex);
                if (strip > 0f && f % Mathf.Max(1, Mathf.RoundToInt(strip * Fps)) == 0)
                    File.WriteAllBytes(Path.Combine(ShotDir, $"flow_{v.name}{suffix}_s{f / Mathf.Max(1, Mathf.RoundToInt(strip * Fps))}.png"), all[all.Count - 1]);
                if (prev != null)
                {
                    double s = 0; for (int i = 0; i < lum.Length; i++) s += Math.Abs(lum[i] - prev[i]);
                    trace.Add((clock, s / lum.Length));
                }
                prev = lum;
            }
            var sorted = trace.Select(t => t.change).OrderBy(x => x).ToList();
            double median = sorted[sorted.Count / 2];
            var worst = trace.OrderByDescending(t => t.change).First();
            int worstIdx = trace.IndexOf(worst) + 1;   // the frame after the change
            int spikes = trace.Count(t => t.change > SpikeRatio * median);
            bool pass = spikes == 0;
            ok &= pass;
            // the frames round the worst change: the two before, the one after it, and the one after that
            var pics = new List<string>();
            foreach (int k in new[] { worstIdx - 2, worstIdx - 1, worstIdx, worstIdx + 1 })
            {
                if (k < 0 || k >= all.Count) continue;
                string p = Path.Combine(ShotDir, $"flow_{v.name}{suffix}_{k - worstIdx + 2}.png");
                File.WriteAllBytes(p, all[k]);
                pics.Add(Path.GetFileName(p));
            }
            all.Clear();
            File.WriteAllLines(Path.Combine(repDir, $"TornadoFlowCheck_{v.name}{suffix}.csv"),
                new[] { "clock_s,mean_change" }.Concat(trace.Select(t => $"{t.clock:0.000},{t.change:0.000}")));
            rep.AppendLine($"| {v.name} | {median:0.00} | {worst.change:0.00} | {worst.clock:0.00} s | {worst.change / Math.Max(median, 1e-6):0.0}x | {spikes} | {(pass ? "PASS" : "FAIL")} (`Screenshots/{string.Join("`, `", pics)}`) |");
            Debug.Log($"[TornadoFlow] {v.name}: median {median:0.00}, worst {worst.change:0.00} at {worst.clock:0.00} s ({worst.change / Math.Max(median, 1e-6):0.0}x), {spikes} spikes {(pass ? "PASS" : "FAIL")}");
        }
        storm.Tornadoes = natural;
        string report = Path.Combine(repDir, $"TornadoFlowCheck{suffix}.md");
        File.WriteAllText(report, rep.ToString());
        Debug.Log($"[TornadoFlow] {(ok ? "PASS" : "FAIL")}; report {report}");
        return ok;
    }

    /// <summary>The march's light (HDRP units, transmittance in a) as an 8-bit image: 1 - exp(-light) over grey (as StormPerfCheck).</summary>
    static Texture2D Grab(RenderTexture rt)
    {
        var prev = RenderTexture.active; RenderTexture.active = rt;
        var tex = new Texture2D(rt.width, rt.height, TextureFormat.RGBAHalf, false, true);
        tex.ReadPixels(new Rect(0, 0, rt.width, rt.height), 0, 0); tex.Apply();
        RenderTexture.active = prev;
        var px = tex.GetPixels();
        for (int i = 0; i < px.Length; i++)
        {
            var c = px[i]; float bg = 0.35f * c.a;
            px[i] = new Color(1f - Mathf.Exp(-(c.r + bg)), 1f - Mathf.Exp(-(c.g + bg)), 1f - Mathf.Exp(-(c.b + bg)), 1f);
        }
        var o = new Texture2D(rt.width, rt.height, TextureFormat.RGB24, false);
        o.SetPixels(px); o.Apply();
        Object.DestroyImmediate(tex);
        return o;
    }
}
