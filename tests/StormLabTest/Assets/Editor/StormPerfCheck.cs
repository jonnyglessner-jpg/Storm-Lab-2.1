// What the storm costs a frame on this GPU, at the game's settings and a 3440 x 1440 screen (the user's, 2026-10-30:
// "spec is to my GPU", an RX 7900 XT): the march (and its temporal resolve) in the views a chaser sees, a close tornado
// of each kind, two storms at once, the volume's repaint and relight, and the CPU's share. Each view's image is kept
// as a baseline, so an optimisation can be checked against it (mean and 99th percentile difference, 0-255).
//   StormLab > Perf Check
// Batch: -executeMethod StormPerfCheck.RunFromCommandLine [-slPerfBaseline] [-slPerfQuality <tier>] [-slPerfW w -slPerfH h]
// (never with -nographics). -slPerfBaseline writes the images the next runs compare with. Report:
// validation/reports/StormPerf.md (StormPerf_<tier>.md for a tier), images Screenshots/perf_*.png.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using StormLab;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using Debug = UnityEngine.Debug;
using Object = UnityEngine.Object;

public static class StormPerfCheck
{
    static string ShotDir => Path.Combine(StormLabTestKit.ProjectDir, "Screenshots");
    static int W = 3440, H = 1440;

    [MenuItem("StormLab/Perf Check")]
    public static void RunMenu() => Run(false, null);

    public static void RunFromCommandLine()
    {
        var a = System.Environment.GetCommandLineArgs();
        string Arg(string k) { int i = Array.IndexOf(a, k); return i >= 0 && i + 1 < a.Length ? a[i + 1] : null; }
        if (int.TryParse(Arg("-slPerfW"), out var w)) W = w;
        if (int.TryParse(Arg("-slPerfH"), out var h)) H = h;
        diag = a.Contains("-slPerfDiag");
        only = Arg("-slPerfOnly");
        StormRenderer.FullKernelOnly = a.Contains("-slPerfFull");
        bool ok;
        try { ok = Run(a.Contains("-slPerfBaseline"), Arg("-slPerfQuality")); }
        catch (Exception e) { Debug.LogException(e); ok = false; }
        EditorApplication.Exit(ok ? 0 : 1);
    }

    static StormRenderer storm, storm2; static Camera cam;
    /// <summary>-slPerfDiag: where each view's time goes (steps a pixel, without the tornado's light tests, without its fields)</summary>
    static bool diag;
    /// <summary>-slPerfOnly a,b: only these views (experiments); -slPerfFull: the full kernel everywhere</summary>
    static string only;

    static void Setup()
    {
        StormLabTestKit.EnsurePipeline();
        EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        ShaderUtil.allowAsyncCompilation = false;
        var camGo = new GameObject("Main Camera") { tag = "MainCamera" };
        cam = camGo.AddComponent<Camera>();
        cam.nearClipPlane = 0.3f; cam.farClipPlane = 400000f;
        StormLabTestKit.SetupCamera(camGo);
        // the game's settings: the renderer's defaults (unified lighting, detailed tornado, enhanced detail, half-resolution
        // march, temporal resolve), a late-afternoon sun
        storm = new GameObject("Storm").AddComponent<StormRenderer>();
        storm.playing = false;
        storm.sunSource = SunSource.Fixed; storm.sunAzimuth = 255f; storm.sunElevation = 25f;
    }

    struct View { public string name, what; public Func<bool> place; public bool two; }

    static Vector3 Bearing(float deg) { float r = deg * Mathf.Deg2Rad; return new Vector3(Mathf.Sin(r), 0f, Mathf.Cos(r)); }
    static void Look(Vector3 from, Vector3 at, float fov)
    {
        cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(at - from, Vector3.up));
        cam.fieldOfView = fov;
    }

    static bool Run(bool baseline, string tier)
    {
        Setup();
        if (!string.IsNullOrEmpty(tier))
        {
            if (!Enum.TryParse<StormPerformance>(tier, true, out var p)) { Debug.LogError($"[StormPerf] no tier '{tier}'"); return false; }
            storm.performance = p;
        }
        var rep = new StringBuilder("# Storm frame cost\n\n");
        rep.AppendLine($"Generated by `StormPerfCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}, {SystemInfo.graphicsDeviceName}, {W} x {H}" +
                       $", tier {storm.performance}. GPU times are synchronised command buffers of 8 frames " +
                       "(march and temporal resolve; the composite is a full-screen blend of about 0.1 ms). Image difference against the " +
                       "baseline (`-slPerfBaseline`): mean / 99th percentile per-pixel difference, 0-255, after 16 frames.").AppendLine();

        storm.preset = "plains"; storm.varied = true; storm.seed = 42; storm.Replan();
        var P = storm.Plan;
        float form = P.cycles != null ? (float)P.cycles[0].times[2] : 48f;
        float mature = form + 4f;

        // ------------------------------------------------------------------ views
        Vector3 Ground(Vector3 s) { var w = storm.StormToWorld(s); w.y = 0f; return w; }
        var F = storm.Frame.param;
        Vector3 ToSun() { var k = storm.Lighting.keyDir; return new Vector3(k.x, 0f, k.y).normalized; }
        bool At(float t) { storm.StepTo(t, 100f, true); StormLabTestKit.Sync(); return true; }
        TornadoCharacter[] natural = null;
        bool Forced(FunnelShape shape, double w, int ef, float km, float up)
        {
            storm.Replan(); natural ??= storm.Tornadoes;
            var forced = StormTornadoes.Forced(P, ClimoRegion.Plains, 0, shape, w, ef);
            if (forced == null) return false;
            if (shape == FunnelShape.Wedge)
            {
                double k = w / 2000.0 / forced.groundKm;
                forced.groundKm *= k; forced.topKm *= k; forced.rcKm = Math.Min(forced.rcKm * k, 0.6); forced.widthM = w;
                for (int i = 0; i < forced.phases.Length; i++) { var p = forced.phases[i]; p.groundKm *= k; p.topKm *= k; forced.phases[i] = p; }
            }
            var chars = storm.Tornadoes; chars[0] = forced; storm.Tornadoes = chars;
            float T = (float)(forced.formMin + (shape == FunnelShape.Wedge ? 0.55 : 0.4) * forced.LifeMin);
            At(T);
            var g = storm.TornadoGroundWorld; g.y = 0f;
            float zb = (float)(P.zb - StormDesign.CLOUD_BASE_LIFT_KM);
            float D = storm.Frame.param[14 * 4] * 1000f + km * 1000f;
            var from = g + Bearing(140f) * D + Vector3.up * up;
            Look(from, up > 10f ? g + Vector3.up * 30f : g + Vector3.up * zb * 400f, 60f);
            return true;
        }
        bool Chaser(float t, float km, float side, float aimKm, float fov)
        {
            At(t);
            var u = storm.UpdraftWorld(storm.StormTime); u.y = 0f;
            var ffd = Ground(new Vector3(F[9 * 4], F[9 * 4 + 1], 0f));
            var fa = u + Quaternion.Euler(0, side, 0) * ToSun() * km * 1000f;
            var fb = u + Quaternion.Euler(0, -side, 0) * ToSun() * km * 1000f;
            var from = ((fa - ffd).sqrMagnitude >= (fb - ffd).sqrMagnitude ? fa : fb) + Vector3.up * 2f;
            Look(from, new Vector3(u.x, aimKm * 1000f, u.z), fov);
            return true;
        }
        var views = new List<View>
        {
            new View { name = "far_25km", what = "the mature storm from 25 km", place = () => Chaser(mature, 25f, 70f, 5f, 70f) },
            new View { name = "base_10km", what = "the base and updraft from 10 km", place = () => Chaser(mature, 10f, 60f, 1.5f, 70f) },
            new View { name = "under_3km", what = "under the base's edge, 3 km from the updraft", place = () => Chaser(mature, 3f, 90f, 1.6f, 75f) },
            new View { name = "in_rain", what = "inside the forward-flank rain, looking at the updraft", place = () =>
            {
                At(mature); var r = Ground(new Vector3(F[9 * 4], F[9 * 4 + 1], 0f)) + Vector3.up * 2f;
                var u = storm.UpdraftWorld(storm.StormTime); Look(r, new Vector3(u.x, 600f, u.z), 75f); return true;
            } },
            new View { name = "backlit_15km", what = "the storm against the sun from 15 km", place = () => Chaser(mature, 15f, 165f, 2f, 70f) },
            new View { name = "young_8km", what = "the young storm (towering cumulus to first anvil) from 8 km", place = () => Chaser(Mathf.Max(form - 25f, 5f), 8f, 60f, 3f, 70f) },
            new View { name = "rope_0.4km", what = "a rope tornado 0.4 km away", place = () => Forced(FunnelShape.Rope, 90, 1, 0.4f, 2f) },
            new View { name = "cone_0.4km", what = "a cone tornado 0.4 km away", place = () => Forced(FunnelShape.Cone, 350, 2, 0.4f, 2f) },
            new View { name = "wedge_1.5km", what = "a 1 km wedge 1.5 km away (the worst case measured 2026-10-27)", place = () => Forced(FunnelShape.Wedge, 1800, 4, 1.5f, 2f) },
            new View { name = "wedge_0.4km_up", what = "a 1 km wedge from 250 m up in its dust", place = () => Forced(FunnelShape.Wedge, 1800, 4, 0.4f, 250f) },
            new View { name = "two_storms", what = "a game's two storms (26 km apart), the near one's base from 10 km", two = true, place = () => Chaser(mature, 10f, 60f, 1.5f, 70f) },
        };

        double SyncMs() { var sw = Stopwatch.StartNew(); StormLabTestKit.Sync(); return sw.Elapsed.TotalMilliseconds; }
        RenderTexture MarchAll(UnityEngine.Rendering.CommandBuffer cmd, bool two)
        {
            if (!two) return storm.RecordMarch(cmd, cam, null, W, H, false, out _);
            // as StormCustomPass: farther first, each with the other's half-distance from its last march
            var far = storm2; var near = storm;
            far.RecordMarch(cmd, cam, null, W, H, false, out _, near.HalfFor(cam));
            return near.RecordMarch(cmd, cam, null, W, H, false, out _, far.HalfFor(cam));
        }
        double Timed(int reps, bool two)
        {
            using (var warm = new UnityEngine.Rendering.CommandBuffer()) { MarchAll(warm, two); MarchAll(warm, two); Graphics.ExecuteCommandBuffer(warm); }
            StormLabTestKit.Sync();
            double idle = Enumerable.Range(0, 5).Select(_ => SyncMs()).Min();
            var runs = new List<double>();
            for (int r = 0; r < 3; r++)
                using (var cmd = new UnityEngine.Rendering.CommandBuffer { name = "StormPerf timing" })
                {
                    for (int i = 0; i < reps; i++) MarchAll(cmd, two);
                    var sw = Stopwatch.StartNew();
                    Graphics.ExecuteCommandBuffer(cmd); StormLabTestKit.Sync();
                    runs.Add(Math.Max(0, sw.Elapsed.TotalMilliseconds - idle) / reps);
                }
            return runs.Min();
        }

        rep.AppendLine(diag ? "| view | what | march + resolve | image vs baseline | steps a pixel: mean / in the tornado / 95th percentile | without the tornado's light tests | without its fields |\n| --- | --- | --- | --- | --- | --- | --- |"
                            : "| view | what | march + resolve | image vs baseline |\n| --- | --- | --- | --- |");
        bool ok = true; var total = new List<double>(); double worst = 0; string worstName = "";
        var diffs = new List<(string, double, int)>();
        foreach (var v in views)
        {
            if (only != null && !only.Split(',').Contains(v.name)) continue;
            storm.Tornadoes = natural ?? storm.Tornadoes;
            if (!v.place()) { rep.AppendLine($"| {v.name} | {v.what} | FAIL: could not place | |"); ok = false; continue; }
            if (v.two)
            {
                if (!storm2)
                {
                    storm2 = new GameObject("Storm 2").AddComponent<StormRenderer>();
                    storm2.playing = false; storm2.drawAlongside = true;
                    storm2.sunSource = SunSource.Fixed; storm2.sunAzimuth = storm.sunAzimuth; storm2.sunElevation = storm.sunElevation;
                    storm2.performance = storm.performance;
                    storm2.preset = "plains"; storm2.varied = true; storm2.seed = 4242; storm2.Replan();
                }
                // its updraft 26 km across the motion from the first's, 8 storm minutes younger
                var mot = new Vector3((float)P.motion.x, 0f, (float)P.motion.y).normalized;
                var across = Vector3.Cross(Vector3.up, mot);
                var u1 = storm.UpdraftWorld(storm.StormTime); u1.y = 0f;
                storm2.PlaceUpdraftAt(u1 - across * 26000f, mature - 8f);
                storm2.StepTo(mature - 8f, 100f, true); StormLabTestKit.Sync();
                storm.Activate();
            }
            storm.ResetHistory(cam); if (storm2) storm2.ResetHistory(cam);
            double ms = Timed(8, v.two);
            total.Add(ms); if (ms > worst) { worst = ms; worstName = v.name; }
            // the image after 16 frames of temporal resolve
            storm.ResetHistory(cam); if (storm2) storm2.ResetHistory(cam);
            RenderTexture rt = null;
            for (int f = 0; f < 16; f++)
                using (var cmd = new UnityEngine.Rendering.CommandBuffer()) { rt = MarchAll(cmd, v.two); Graphics.ExecuteCommandBuffer(cmd); }
            string img = Path.Combine(ShotDir, $"perf_{v.name}{(string.IsNullOrEmpty(tier) ? "" : "_" + tier)}.png");
            string basePath = Path.Combine(ShotDir, $"perf_base_{v.name}.png");
            Save(rt, img);
            string cmp = "";
            if (baseline) { File.Copy(img, basePath, true); cmp = "baseline"; }
            else if (File.Exists(basePath)) { var (mean, p99) = Diff(basePath, img); diffs.Add((v.name, mean, p99)); cmp = $"{mean:0.00} / {p99}"; }
            string extra = "";
            if (diag)
            {
                var pr = new double[3];
                for (int k = 1; k <= 2; k++) { storm.tornadoCostProbe = k; storm.ResetHistory(cam); pr[k] = Timed(4, v.two); }
                storm.tornadoCostProbe = 3; float tb = storm.temporalBlend; storm.temporalBlend = 1f; storm.ResetHistory(cam);
                RenderTexture srt;
                using (var cmd = new UnityEngine.Rendering.CommandBuffer()) { srt = storm.RecordMarch(cmd, cam, null, W, H, false, out _); Graphics.ExecuteCommandBuffer(cmd); }
                var prev = RenderTexture.active; RenderTexture.active = srt;
                var tex = new Texture2D(srt.width, srt.height, TextureFormat.RGBAFloat, false, true);
                tex.ReadPixels(new Rect(0, 0, srt.width, srt.height), 0, 0); tex.Apply(); RenderTexture.active = prev;
                var px = tex.GetPixels(); var st = px.Select(c => c.r * 1000f).OrderBy(x => x).ToArray();
                // the heat map: red all steps, green those in the tornado (of 300)
                var heat = px.Select(c => new Color(c.r * 1000f / 300f, c.g * 1000f / 300f, 0f, 1f)).ToArray();
                tex.SetPixels(heat); tex.Apply();
                var o = new Texture2D(tex.width, tex.height, TextureFormat.RGB24, false); o.SetPixels(heat); o.Apply();
                File.WriteAllBytes(Path.Combine(ShotDir, $"perf_steps_{v.name}.png"), o.EncodeToPNG());
                Object.DestroyImmediate(o); Object.DestroyImmediate(tex);
                // and by kind (probe 4)
                storm.tornadoCostProbe = 4; storm.ResetHistory(cam);
                using (var cmd = new UnityEngine.Rendering.CommandBuffer()) { srt = storm.RecordMarch(cmd, cam, null, W, H, false, out _); Graphics.ExecuteCommandBuffer(cmd); }
                prev = RenderTexture.active; RenderTexture.active = srt;
                var tk = new Texture2D(srt.width, srt.height, TextureFormat.RGBAFloat, false, true);
                tk.ReadPixels(new Rect(0, 0, srt.width, srt.height), 0, 0); tk.Apply(); RenderTexture.active = prev;
                var pk = tk.GetPixels(); Object.DestroyImmediate(tk);
                string kinds = $"near {pk.Average(c => c.r * 1000f):0}, surface {pk.Average(c => c.g * 1000f):0}, cloud {pk.Average(c => c.b * 1000f):0}, rain {pk.Average(c => c.a * 1000f):0}";
                storm.tornadoCostProbe = 0; storm.temporalBlend = tb; storm.ResetHistory(cam);
                extra = $" {st.Average():0} / {px.Average(c => c.g * 1000f):0} / {st[(int)(st.Length * 0.95)]:0} ({kinds}) | {pr[1]:0.00} ms | {pr[2]:0.00} ms |";
            }
            rep.AppendLine($"| {v.name} | {v.what} | {ms:0.00} ms | {cmp} |{extra}");
            if (v.two && storm2) { Object.DestroyImmediate(storm2.gameObject); storm2 = null; storm.Activate(); }
            Debug.Log($"[StormPerf] {v.name}: {ms:0.00} ms {cmp}");
        }
        storm.Tornadoes = natural ?? storm.Tornadoes;
        if (total.Count > 0) rep.AppendLine().AppendLine($"Mean over the views {total.Average():0.00} ms; worst {worst:0.00} ms ({worstName}).").AppendLine();

        // ------------------------------------------------------------------ the volume
        At(mature);
        double VolMs(Action<UnityEngine.Rendering.CommandBuffer> rec, int reps)
        {
            using (var warm = new UnityEngine.Rendering.CommandBuffer()) { rec(warm); Graphics.ExecuteCommandBuffer(warm); }
            StormLabTestKit.Sync();
            double idle = Enumerable.Range(0, 5).Select(_ => SyncMs()).Min();
            var runs = new List<double>();
            for (int r = 0; r < 3; r++)
                using (var cmd = new UnityEngine.Rendering.CommandBuffer())
                {
                    for (int i = 0; i < reps; i++) rec(cmd);
                    var sw = Stopwatch.StartNew(); Graphics.ExecuteCommandBuffer(cmd); StormLabTestKit.Sync();
                    runs.Add(Math.Max(0, sw.Elapsed.TotalMilliseconds - idle) / reps);
                }
            return runs.Min();
        }
        var vol = storm.Volume; var key = storm.Lighting.keyDir; var param = storm.Frame.param;
        var noiseTex = CloudNoise.Make();
        double full = VolMs(c => vol.Update(c, param, noiseTex, key), 4);
        double relight = VolMs(c => vol.Relight(c, key, param[4]), 4);
        // a repaint spread over frames: each frame's share (the frame that finishes it also relights, unless spread too)
        var steps = new List<double>();
        vol.BeginUpdate(param, noiseTex, key);
        while (vol.Rebuilding)
        {
            using (var cmd = new UnityEngine.Rendering.CommandBuffer())
            {
                StormLabTestKit.Sync(); double idle = SyncMs();
                vol.Step(cmd);
                var sw = Stopwatch.StartNew(); Graphics.ExecuteCommandBuffer(cmd); StormLabTestKit.Sync();
                steps.Add(Math.Max(0, sw.Elapsed.TotalMilliseconds - idle));
            }
        }
        rep.AppendLine($"Volume ({storm.quality}, {vol.NV} x {vol.NV} x {vol.NZ}, {vol.VramBytes / 1048576.0:0} MB): full repaint and relight {full:0.00} ms; relight alone {relight:0.00} ms; " +
                       $"a repaint spread over frames, each frame: {string.Join(", ", steps.Select(s => $"{s:0.00}"))} ms (every {storm.rebuildEvery:0.0} s at most, when storm time has moved 0.05 min or the sun has).").AppendLine();

        // ------------------------------------------------------------------ the CPU
        storm.playing = false;
        var swc = Stopwatch.StartNew(); long gc0 = GC.GetAllocatedBytesForCurrentThread(); int n = 200;
        for (int i = 0; i < n; i++)
        {
            storm.StepTo(mature + i * 0.0003, 100f + i * 0.016f);
            using (var cmd = new UnityEngine.Rendering.CommandBuffer()) storm.RecordMarch(cmd, cam, null, W, H, false, out _);
        }
        double cpu = swc.Elapsed.TotalMilliseconds / n; long gc = (GC.GetAllocatedBytesForCurrentThread() - gc0) / n;
        StormLabTestKit.Sync();
        rep.AppendLine($"CPU (main thread, editor): StepTo + RecordMarch {cpu:0.000} ms a frame, {gc} bytes allocated a frame (includes the timing's own command buffer).").AppendLine();

        string report = Path.Combine(StormLabTestKit.RepoRoot, "validation", "reports", string.IsNullOrEmpty(tier) ? "StormPerf.md" : $"StormPerf_{tier}.md");
        File.WriteAllText(report, rep.ToString());
        Debug.Log($"[StormPerf] {(ok ? "done" : "FAIL")}; report {report}");
        Object.DestroyImmediate(noiseTex);
        return ok;
    }

    /// <summary>The march's light (HDRP units of the storm's light, transmittance in a) as an 8-bit image: 1 - exp(-light) over grey.</summary>
    static void Save(RenderTexture rt, string path)
    {
        var prev = RenderTexture.active; RenderTexture.active = rt;
        var tex = new Texture2D(rt.width, rt.height, TextureFormat.RGBAHalf, false, true);
        tex.ReadPixels(new Rect(0, 0, rt.width, rt.height), 0, 0); tex.Apply();
        RenderTexture.active = prev;
        var px = tex.GetPixels();
        for (int i = 0; i < px.Length; i++)
        {
            var c = px[i]; float bg = 0.35f * c.a;
            px[i] = new Color(1f - Mathf.Exp(-(c.r + bg)), 1f - Mathf.Exp(-(c.g + bg)), 1f - Mathf.Exp(-(c.b + bg)), 1f);
        }
        var o = new Texture2D(rt.width, rt.height, TextureFormat.RGB24, false);
        o.SetPixels(px); o.Apply();
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        File.WriteAllBytes(path, o.EncodeToPNG());
        Object.DestroyImmediate(tex); Object.DestroyImmediate(o);
    }

    static (double mean, int p99) Diff(string a, string b)
    {
        var ta = new Texture2D(2, 2); ta.LoadImage(File.ReadAllBytes(a));
        var tb = new Texture2D(2, 2); tb.LoadImage(File.ReadAllBytes(b));
        if (ta.width != tb.width || ta.height != tb.height)
        {
            // a tier marching at another resolution: compare at the baseline's size
            var rt = RenderTexture.GetTemporary(ta.width, ta.height); Graphics.Blit(tb, rt);
            var prev = RenderTexture.active; RenderTexture.active = rt;
            tb.Reinitialize(ta.width, ta.height); tb.ReadPixels(new Rect(0, 0, ta.width, ta.height), 0, 0); tb.Apply();
            RenderTexture.active = prev; RenderTexture.ReleaseTemporary(rt);
        }
        var pa = ta.GetPixels32(); var pb = tb.GetPixels32();
        var hist = new int[256]; double s = 0;
        for (int i = 0; i < pa.Length; i++)
        {
            int d = Math.Max(Math.Abs(pa[i].r - pb[i].r), Math.Max(Math.Abs(pa[i].g - pb[i].g), Math.Abs(pa[i].b - pb[i].b)));
            hist[d]++; s += d;
        }
        Object.DestroyImmediate(ta); Object.DestroyImmediate(tb);
        int p = 0, acc = 0; while (p < 255 && (acc += hist[p]) < pa.Length * 0.99) p++;
        return (s / pa.Length, p);
    }
}
