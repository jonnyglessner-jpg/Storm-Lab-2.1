// Where the test map's storms start and come in (TestMapWorld.SpawnStorm), for every setup and seeds 1-12, without Play:
// at storm time 0 the storm must be towering cumulus, off the map, within the start bearings (west to south); its updraft
// must cross onto the map just before it is fully mature and be over the map then; and the tracks must differ by seed.
// Writes validation/reports/StormSpawnCheck.md and validation/reports/storm_tracks.csv (for the track map).
//   StormLab > Test Map > Storm Spawn Check
// Batch: -executeMethod StormSpawnCheck.RunFromCommandLine
using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using StormLab;
using StormLab.TestMap;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

public static class StormSpawnCheck
{
    [MenuItem("StormLab/Test Map/Storm Spawn Check")]
    public static void RunMenu() => Run();

    public static void RunFromCommandLine()
    {
        bool ok;
        try { ok = Run(); }
        catch (Exception e) { Debug.LogException(e); ok = false; }
        EditorApplication.Exit(ok ? 0 : 1);
    }

    public static bool Run()
    {
        EditorSceneManager.OpenScene(TestMapBuilder.ScenePath, OpenSceneMode.Single);
        var world = UnityEngine.Object.FindAnyObjectByType<TestMapWorld>();
        var storm = world.storm;
        float half = world.sizeM / 2;
        var inv = CultureInfo.InvariantCulture;
        var rep = new StringBuilder("# Storm spawn check\n\n");
        var csv = new StringBuilder("preset,seed,kind,startX,startZ,entryX,entryZ,matureX,matureZ,endX,endZ,entryMin,matureMin,bearing\n");
        rep.AppendLine($"Generated by `StormSpawnCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}. Map {world.sizeM / 1609.344f:0} x {world.sizeM / 1609.344f:0} miles centred on the world origin; start bearings {world.startBearings.x:0}-{world.startBearings.y:0} deg; the updraft comes on {world.enterBeforeMature:0.#} min before maturity.").AppendLine();
        rep.AppendLine("| Setup | Moves toward | Speed | Seeds | Start bearings | Start off the map by | Onto the map at | Mature at | Inside at maturity | Stage at 0 | Result |").AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
        bool all = true;
        foreach (var pre in StormPreset.All)
        {
            int good = 0, n = 0, otherSide = 0; float bMin = 999, bMax = -999, offMin = 1e9f, offMax = 0, inMin = 1e9f; string stage0 = ""; bool stageOk = true;
            double motionAz = 0, speed = 0; float eMin = 1e9f, eMax = 0, mMin = 1e9f, mMax = 0;
            var entries = new System.Collections.Generic.HashSet<string>();
            for (int seed = 1; seed <= 12; seed++, n++)
            {
                storm.preset = pre.key; storm.varied = true; storm.seed = seed; storm.Replan();
                world.SpawnStorm();
                var P = storm.Plan;
                motionAz = (Math.Atan2(P.motion.x, P.motion.y) * 180 / Math.PI + 360) % 360; speed = Math.Sqrt(P.motion.x * P.motion.x + P.motion.y * P.motion.y);
                // the stage at storm time 0
                var f = StormDesign.At(P, 0, 0);
                stage0 = f.stage;
                if (P.kind == StormKind.Supercell || P.kind == StormKind.Pulse) stageOk &= f.stage == "Towering cumulus";
                Vector3 S = storm.UpdraftWorld(0), E = storm.UpdraftWorld(world.EntryMinutes), M = storm.UpdraftWorld(world.MatureMinutes), End = storm.UpdraftWorld(P.duration);
                float Out(Vector3 p) => Mathf.Max(Mathf.Abs(p.x), Mathf.Abs(p.z)) - half;   // > 0 off the map
                float bearing = (Mathf.Atan2(S.x, S.z) * Mathf.Rad2Deg + 360f) % 360f;
                bool startOff = Out(S) > 100f, inBearing = bearing >= world.startBearings.x - 0.5f && bearing <= world.startBearings.y + 0.5f;
                if (!world.FromAllowedSide) { otherSide++; inBearing = true; }   // its motion cannot bring it in from there
                bool onEdge = Mathf.Abs(Out(E)) < 50f, matureIn = Out(M) < 0f;
                if (startOff && inBearing && onEdge && matureIn) good++;
                bMin = Mathf.Min(bMin, bearing); bMax = Mathf.Max(bMax, bearing);
                offMin = Mathf.Min(offMin, Out(S)); offMax = Mathf.Max(offMax, Out(S)); inMin = Mathf.Min(inMin, -Out(M));
                eMin = Mathf.Min(eMin, world.EntryMinutes); eMax = Mathf.Max(eMax, world.EntryMinutes);
                mMin = Mathf.Min(mMin, world.MatureMinutes); mMax = Mathf.Max(mMax, world.MatureMinutes);
                entries.Add($"{Mathf.Round(E.x / 2000f)},{Mathf.Round(E.z / 2000f)}");
                csv.AppendLine(string.Join(",", pre.key, seed.ToString(inv), P.kind.ToString(), S.x.ToString("0", inv), S.z.ToString("0", inv), E.x.ToString("0", inv), E.z.ToString("0", inv),
                    M.x.ToString("0", inv), M.z.ToString("0", inv), End.x.ToString("0", inv), End.z.ToString("0", inv), world.EntryMinutes.ToString("0.0", inv), world.MatureMinutes.ToString("0.0", inv), bearing.ToString("0", inv)));
            }
            // a storm that does not form (capped, clear) has nothing to mature; it is placed the same way
            bool forms = storm.Plan.kind == StormKind.Supercell || storm.Plan.kind == StormKind.Pulse;
            bool pass = good == n && stageOk && entries.Count >= Math.Min(n, 8);
            all &= pass || !forms;
            rep.AppendLine($"| {pre.key} ({storm.Plan.kind}) | {motionAz:0} deg | {speed:0.0} m/s | {n} | {bMin:0}-{bMax:0} deg | {offMin / 1000:0.0}-{offMax / 1000:0.0} km | {eMin:0.0}-{eMax:0.0} min | {mMin:0.0}-{mMax:0.0} min | {inMin / 1000:0.0} km in or more | {stage0} | " +
                          $"{(pass ? "PASS" : forms ? "FAIL" : "n/a (no storm forms)")}: {good}/{n} tracks fit, {entries.Count} different entry points{(otherSide > 0 ? $"; {otherSide} start on the side its motion comes from, not west to south" : "")} |");
        }
        rep.AppendLine().AppendLine("Inside at maturity: how far inside the map's edge the updraft is when the storm is fully mature (the nearest edge). Tracks: `storm_tracks.csv`, drawn in `storm_tracks.png`.");
        string dir = Path.Combine(StormLabTestKit.RepoRoot, "validation", "reports");
        Directory.CreateDirectory(dir);
        File.WriteAllText(Path.Combine(dir, "StormSpawnCheck.md"), rep.ToString());
        File.WriteAllText(Path.Combine(dir, "storm_tracks.csv"), csv.ToString());
        Debug.Log($"[StormSpawn] {(all ? "PASS" : "FAIL")}");
        return all;
    }
}
