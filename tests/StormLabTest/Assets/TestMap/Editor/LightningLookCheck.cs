// Play-mode look check of the lightning's bolts: enters Play on the test map, holds the storm at its first mature cycle at
// dusk, and photographs flashes of each kind at their peak from a chaser's spot 12 km off: ground bolts that reach out of
// the storm's side before they strike, positive bolts out of the anvil, the plain drops through the base, in-cloud flashes
// and anvil crawlers (at their first pulse and late in their flicker). Each flash's geometry is measured (how far out it
// strikes, its ground contacts, its longest branch, a crawler's extent and lowest point). Screenshots/lightning_*.png and a
// contact sheet lightning_sheet.jpg, validation/reports/LightningLookCheck.md.
//   StormLab > Test Map > Lightning Look Check
// Batch: -executeMethod LightningLookCheck.RunFromCommandLine [-slBoltHour h] (never with -nographics)
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using StormLab;
using StormLab.Lightning;
using StormLab.TestMap;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using Object = UnityEngine.Object;
using NVector3 = System.Numerics.Vector3;

[InitializeOnLoad]
public static class LightningLookCheck
{
    const string Key = "LightningLookCheck.Active", BatchKey = "LightningLookCheck.Batch", CodeKey = "LightningLookCheck.Code";
    static string ShotDir => Path.Combine(StormLabTestKit.ProjectDir, "Screenshots");
    static string ReportPath => Path.Combine(StormLabTestKit.RepoRoot, "validation", "reports", "LightningLookCheck.md");

    static LightningLookCheck() { if (SessionState.GetBool(Key, false)) EditorApplication.playModeStateChanged += OnState; }

    [MenuItem("StormLab/Test Map/Lightning Look Check")]
    public static void RunMenu() => Begin(false);
    public static void RunFromCommandLine() => Begin(true);

    static void Begin(bool batch)
    {
        EditorSceneManager.OpenScene(TestMapBuilder.ScenePath, OpenSceneMode.Single);
        SessionState.SetBool(Key, true); SessionState.SetBool(BatchKey, batch);
        EditorApplication.playModeStateChanged -= OnState;
        EditorApplication.playModeStateChanged += OnState;
        EditorApplication.EnterPlaymode();
    }

    static IEnumerator<object> routine; static readonly StringBuilder rep = new StringBuilder(); static bool ok; static int errors;
    static readonly List<string> errorLines = new List<string>();

    static void OnState(PlayModeStateChange s)
    {
        if (s == PlayModeStateChange.EnteredPlayMode)
        {
            rep.Clear(); ok = true; errors = 0; errorLines.Clear();
            Application.logMessageReceived += OnLog;
            routine = Run().GetEnumerator();
            EditorApplication.update += Tick;
        }
        else if (s == PlayModeStateChange.EnteredEditMode && SessionState.GetBool(Key, false))
        {
            SessionState.SetBool(Key, false);
            EditorApplication.playModeStateChanged -= OnState;
            if (SessionState.GetBool(BatchKey, false)) EditorApplication.Exit(SessionState.GetInt(CodeKey, 1));
        }
    }

    static void OnLog(string msg, string stack, LogType t)
    {
        if (t != LogType.Error && t != LogType.Exception && t != LogType.Assert) return;
        if (stack != null && stack.Contains("UnityEditor.Search")) return;
        errors++; if (errorLines.Count < 10) errorLines.Add($"{t}: {msg.Split('\n')[0]}");
    }

    static void Tick()
    {
        if (!EditorApplication.isPlaying) return;
        bool more;
        try { more = routine.MoveNext(); }
        catch (Exception e) { Debug.LogException(e); ok = false; more = false; }
        if (more) return;
        EditorApplication.update -= Tick;
        Application.logMessageReceived -= OnLog;
        rep.AppendLine().AppendLine($"Errors logged: {errors}");
        foreach (var l in errorLines) rep.AppendLine($"- {l}");
        ok &= errors == 0;
        rep.Insert(0, $"# Lightning look check: {(ok ? "PASS" : "FAIL")}\n\nGenerated by `LightningLookCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}, {SystemInfo.graphicsDeviceName}.\n\n");
        Directory.CreateDirectory(Path.GetDirectoryName(ReportPath));
        File.WriteAllText(ReportPath, rep.ToString());
        Debug.Log($"[LightningLook] {(ok ? "PASS" : "FAIL")}; report {ReportPath}");
        SessionState.SetInt(CodeKey, ok ? 0 : 1);
        EditorApplication.ExitPlaymode();
    }

    static IEnumerable<object> Frames(int n) { for (int i = 0; i < n; i++) yield return null; }
    static IEnumerable<object> PlayerFrames(int n) { int f0 = Time.frameCount; while (Time.frameCount < f0 + n) yield return null; }

    sealed class Case
    {
        public string name; public FlashKind kind; public int shots; public float reaching = .6f; public float aimUp = 3500f;
        public float[] ages = { .04f }; public float hour = -1; public bool underAnvil;
        // ages as fractions of the flash's LeadSeconds (a crawler's crawl is a second or two, its own per flash)
        public bool leadFractions;
        public LightningActivity Activity => new LightningActivity(30,
            kind == FlashKind.NegativeGround || kind == FlashKind.PositiveGround ? 1 : 0, kind == FlashKind.PositiveGround ? 1 : 0, .5f,
            kind == FlashKind.Crawler ? 1 : 0);
    }

    static IEnumerable<object> Run()
    {
        foreach (var x in Frames(30)) yield return x;
        var world = Object.FindAnyObjectByType<TestMapWorld>();
        var panel = world ? world.GetComponent<TestMapStormPanel>() : null;
        var storm = world ? world.storm : null;
        var cam = Camera.main;
        var sl = storm ? storm.GetComponent<StormLightning>() : null;
        if (!panel || !storm || !cam || !sl) { ok = false; rep.AppendLine($"FAIL: panel {panel}, storm {storm}, camera {cam}, lightning {sl}"); yield break; }
        var rig = cam.GetComponent<TestMapCamera>(); if (rig) rig.enabled = false;
        var argv = System.Environment.GetCommandLineArgs(); int hi = Array.IndexOf(argv, "-slBoltHour");
        float hour = hi >= 0 && hi + 1 < argv.Length ? float.Parse(argv[hi + 1], System.Globalization.CultureInfo.InvariantCulture) : 20.1f;
        storm.playing = false;
        var P = storm.Plan;
        float t = P.cycles != null ? (float)P.cycles[0].times[3] : 50f;
        storm.StormTime = t;
        world.PlaceStorm();
        storm.StepTo(t, storm.Clock, true);
        panel.hour = hour; panel.moonPhase = .5f; panel.clockRuns = false; panel.Apply();
        // the chaser, 12 km from the updraft, square to the storm's motion
        var u = storm.UpdraftWorld(t);
        var target = new Vector3(u.x, 0, u.z);
        var mv = new Vector3((float)P.motion.x, 0, (float)P.motion.y).normalized;
        var from = target + Quaternion.Euler(0, 110, 0) * mv * 12000f;
        from.y = Physics.Raycast(from + Vector3.up * 3000f, Vector3.down, out var hit, 6000f) ? hit.point.y + 2f : 2f;
        cam.fieldOfView = 65f;
        void Aim(float up) => cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(new Vector3(target.x, from.y + up, target.z) - from, Vector3.up));
        Aim(3500f);
        // let the storm, its volume and the lightning bind
        foreach (var x in PlayerFrames(12)) yield return x;
        if (!sl.Bind() || !storm.ReadyToRender) { ok = false; rep.AppendLine("FAIL: the lightning did not bind or the storm is not ready to render"); yield break; }
        rep.AppendLine($"Storm: {storm.preset} seed {storm.seed} at {t:0.0} min ({storm.Frame.stage}); camera 12 km off the updraft, {hour:0.0} h; the storm's lightning activity then: {sl.Flashes.CurrentActivity}.").AppendLine();
        // this check drives the flashes itself: one kind at a time at 30 candidates a minute, every candidate accepted
        sl.enabled = false;
        var flashes = sl.Flashes;
        flashes.thunder = false; flashes.advanceClock = false;
        var cases = new[]
        {
            new Case { name = "reaching", kind = FlashKind.NegativeGround, shots = 3, reaching = 1 },
            new Case { name = "anvil_positive", kind = FlashKind.PositiveGround, shots = 2, reaching = 1, aimUp = 4500f },
            new Case { name = "drop", kind = FlashKind.NegativeGround, shots = 1, reaching = 0 },
            new Case { name = "incloud", kind = FlashKind.InCloud, shots = 1, aimUp = 5000f },
            // a crawler mid-crawl (the leader half way out, its legs sprouting behind it) and just after it has formed
            new Case { name = "crawler", kind = FlashKind.Crawler, shots = 3, aimUp = 8000f, ages = new[] { .45f, 1f }, leadFractions = true },
            new Case { name = "crawler_under", kind = FlashKind.Crawler, shots = 2, underAnvil = true, ages = new[] { .45f, 1f }, leadFractions = true },
            new Case { name = "reaching_day", kind = FlashKind.NegativeGround, shots = 2, reaching = 1, hour = 16f },
        };
        // under the anvil: a chaser 9 km downwind of the updraft looking up along it
        var anvilDir = new Vector3((float)P.adir.x, 0, (float)P.adir.y).normalized;
        var fromUnder = target + anvilDir * 9000f;
        fromUnder.y = Physics.Raycast(fromUnder + Vector3.up * 3000f, Vector3.down, out var hitU, 6000f) ? hitU.point.y + 2f : 2f;
        var aimUnder = target + anvilDir * 15000f + Vector3.up * 9500f;
        // the lines are sized for the camera's own view (640 x 480 in batch); size them for the 900-line capture instead,
        // at the game's 2 px core (a thinner core breaks into dots on the diagonal)
        float px0 = flashes.minimumPixelWidth;
        flashes.minimumPixelWidth = Mathf.Max(.5f, 2f * cam.pixelHeight / 900f);
        rep.AppendLine("| shot | kind | channels | origin AGL | strikes | out from origin | longest branch | ground contacts | lowest point AGL | extent | far end |").AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
        var shots = new List<string>();
        int reachingOut = 0, reachingTried = 0, contactsOff = 0, crawlersLow = 0, crawlersShort = 0, crawlersAtOnce = 0, missing = 0, branchesBusy = 0;
        var events = new List<FlashEvent>();
        float Terrain(Vector3 p) => Physics.Raycast(p + Vector3.up * 3000f, Vector3.down, out var h, 6000f) ? h.point.y : storm.origin.y;
        for (int ci = 0; ci < cases.Length; ci++)
        {
            var c = cases[ci];
            if (c.underAnvil) cam.transform.SetPositionAndRotation(fromUnder, Quaternion.LookRotation(aimUnder - fromUnder, Vector3.up));
            else Aim(c.aimUp);
            if (c.hour > 0)
            {
                panel.hour = c.hour; panel.Apply();
                foreach (var x in PlayerFrames(40)) yield return x;   // the exposure settles
            }
            // what StormLightning's LateUpdate would set each frame (it is off while this check drives the flashes)
            flashes.lightScale = storm.LightningScale;
            flashes.settings.maxFlashesPerMinute = 30; flashes.settings.reachingGroundFraction = c.reaching;
            var activity = c.Activity;
            flashes.ActivityAtTime = _ => activity;
            flashes.ResetPlayback();
            double t0 = 1000 + ci * 300;
            LightningSchedule.Query(flashes.settings, t0, t0 + 200, events, _ => activity);
            int got = 0;
            foreach (var e in events)
            {
                if (got >= c.shots) break;
                flashes.SampleAt(e.time - .005);
                flashes.SampleAt(e.time + .02);
                if (!flashes.TryGetFlash(e.id, out var flash)) continue;   // no cloud anchor for this candidate: the next
                float Age(int i) => c.leadFractions ? flash.LeadSeconds * c.ages[i] : c.ages[i];
                flashes.SampleAt(e.time + Age(0));
                if (!flashes.TryGetFlash(e.id, out flash)) continue;
                got++;
                if (c.kind == FlashKind.Crawler)
                {
                    // a crawler fans out where its anchors put it: look at the middle of this one from the chosen spot
                    var sum = Vector3.zero; int n = 0;
                    foreach (var ch in flash.Channels) foreach (var p in ch.points) { sum += new Vector3(p.X, p.Y, p.Z); n++; }
                    cam.transform.rotation = Quaternion.LookRotation(sum / n - cam.transform.position, Vector3.up);
                }
                // geometry
                var main = flash.Channels[0].points;
                var o = new Vector3(main[0].X, main[0].Y, main[0].Z);
                float lateral = Vector2.Distance(new Vector2(main[0].X, main[0].Z), new Vector2(main[128].X, main[128].Z));
                float longest = 0, lowest = float.MaxValue, extent = 0; int contacts = 0;
                foreach (var ch in flash.Channels)
                {
                    float len = 0; for (int i = 1; i < ch.points.Length; i++) len += NVector3.Distance(ch.points[i], ch.points[i - 1]);
                    if (!ch.main) longest = Mathf.Max(longest, len);
                    foreach (var p in ch.points)
                    {
                        var w = new Vector3(p.X, p.Y, p.Z);
                        lowest = Mathf.Min(lowest, w.y - Terrain(w));
                        extent = Mathf.Max(extent, Vector2.Distance(new Vector2(o.x, o.z), new Vector2(w.x, w.z)));
                    }
                    if (ch.main)
                    {
                        var low = ch.points.OrderBy(p => p.Y).First(); var lw = new Vector3(low.X, low.Y, low.Z);
                        if (Mathf.Abs(lw.y - Terrain(lw)) < 3f) contacts++;
                        else if (c.kind == FlashKind.NegativeGround || c.kind == FlashKind.PositiveGround) contactsOff++;
                    }
                }
                bool groundKind = c.kind == FlashKind.NegativeGround || c.kind == FlashKind.PositiveGround;
                if (c.name == "reaching" || c.name == "anvil_positive" || c.name == "reaching_day") { reachingTried++; if (lateral > 3000f) reachingOut++; }
                if (c.kind == FlashKind.Crawler)
                {
                    if (lowest < 2000f) crawlersLow++; if (extent < 6000f) crawlersShort++;
                    // the crawl: most channels set out after the trunk's leader has run a while, none before it is half out
                    int later = flash.Channels.Count(ch => ch.startAge > .15f * flash.LeadSeconds);
                    if (later < flash.Channels.Length / 2 || flash.LeadSeconds < .5f) crawlersAtOnce++;
                }
                else if (groundKind)
                {
                    // calm branches: a dozen side leaders at most, none over 3.5 km along its bends
                    int sides = flash.Channels.Count(ch => !ch.main);
                    if (sides > 14 || longest > 3500f) branchesBusy++;
                }
                string originAgl = $"{(o.y - Terrain(o)) / 1000:0.0} km";
                var foot = new Vector3(main[128].X, main[128].Y, main[128].Z);
                string where = $"{Vector3.Distance(cam.transform.position, foot) / 1000:0.0} km from the camera" + (groundKind ? $", {Vector2.Distance(new Vector2(foot.x, foot.z), new Vector2(target.x, target.z)) / 1000:0.0} km from the updraft" : "");
                string strikes = c.kind == FlashKind.Crawler ? $"{flash.StrokeTimes.Length} pulses, crawl {flash.LeadSeconds:0.00} s" : flash.StrokeTimes.Length.ToString();
                rep.AppendLine($"| {c.name}_{got} | {c.kind} | {flash.Channels.Length} | {originAgl} | {strikes} | {lateral / 1000:0.0} km | {longest / 1000:0.00} km | {(groundKind ? contacts.ToString() : "-")} | {lowest / 1000:0.00} km | {extent / 1000:0.0} km | {where} |");
                // the pictures: the peak of the first stroke; a crawler half way through its crawl and just after it
                for (int ai = 0; ai < c.ages.Length; ai++)
                {
                    if (ai > 0) flashes.SampleAt(e.time + Age(ai));
                    // the march spreads a flash's relight over frames: let it settle on this moment before the picture
                    foreach (var x in PlayerFrames(4)) yield return x;
                    string name = $"lightning_{c.name}_{got}" + (c.ages.Length > 1 ? $"_{Age(ai) * 1000:000}ms" : "") + ".png";
                    Save(cam, flashes, Path.Combine(ShotDir, name));
                    shots.Add(name);
                    if (c.kind == FlashKind.Crawler)
                    {
                        // the same moment with the cloud's hiding of the channels off: the crawl's shape and how far it has
                        // run, which the anvil hides from most spots on the ground
                        var bridge = sl.Bridge; bool occ = bridge.channelOcclusion;
                        bridge.channelOcclusion = false; bridge.RefreshChannelOcclusion(); yield return null;
                        string clear = name.Replace(".png", "_clear.png");
                        Save(cam, flashes, Path.Combine(ShotDir, clear));
                        shots.Add(clear);
                        bridge.channelOcclusion = occ; bridge.RefreshChannelOcclusion(); yield return null;
                    }
                }
                // -slBoltDebug: for the first reaching bolt, the same frame with the channel occlusion off, 30x the
                // emission and 4 px lines, and the lines' state, to tell a dim bolt from a hidden or missing one
                if (c.name == "reaching" && got == 1 && Array.IndexOf(argv, "-slBoltDebug") >= 0)
                {
                    var bridge = sl.Bridge; bool occ = bridge.channelOcclusion; float em = flashes.emission, px = flashes.minimumPixelWidth;
                    var lines = flashes.transform.GetComponentsInChildren<LineRenderer>(false);
                    var light = flashes.transform.GetComponentInChildren<Light>(false);
                    rep.AppendLine($"Debug: lightScale {flashes.lightScale:0.####}, storm Luminance {storm.Luminance:0.###}, _StormLabLight {Shader.GetGlobalVector("_StormLabLight")}, camera {cam.pixelWidth}x{cam.pixelHeight}, " +
                        $"{lines.Length} lines ({lines.Count(l => l.enabled)} enabled), trunk width {lines[0].widthMultiplier:0.0} m, trunk colour {lines[0].startColor}, material {flashes.ChannelMaterial.GetColor("_Color")}, light {(light ? light.intensity : 0):0} cd.");
                    var shader = flashes.ChannelMaterial.shader;
                    rep.AppendLine($"Debug: shader {shader.name} supported {shader.isSupported}, errors {ShaderUtil.ShaderHasError(shader)}, " +
                        $"camera mask {cam.cullingMask:X}, storm layer {storm.gameObject.layer}, trunk layer {lines[0].gameObject.layer}, trunk bounds {lines[0].bounds}, " +
                        $"trunk first {lines[0].GetPosition(0)}, last {lines[0].GetPosition(lines[0].positionCount - 1)}, camera at {cam.transform.position}, " +
                        $"in frustum {GeometryUtility.TestPlanesAABB(GeometryUtility.CalculateFrustumPlanes(cam), lines[0].bounds)}, material queue {flashes.ChannelMaterial.renderQueue}.");
                    // a fresh 100 m wide line 2 km in front of the camera: with the bolt material, then with HDRP's unlit
                    var probe = new GameObject("Lightning probe line"); probe.hideFlags = HideFlags.DontSave;
                    var pl = probe.AddComponent<LineRenderer>(); pl.useWorldSpace = true; pl.positionCount = 2; pl.widthMultiplier = 100f;
                    var f0 = cam.transform.position + cam.transform.forward * 2000f;
                    pl.SetPosition(0, f0 + Vector3.up * 200f); pl.SetPosition(1, f0 + Vector3.up * 1200f + cam.transform.right * 400f);
                    pl.startColor = pl.endColor = new Color(.004f, .004f, .004f, 1); pl.sharedMaterial = flashes.ChannelMaterial;
                    yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_probe_bolt.png"));
                    pl.startColor = pl.endColor = Color.white; yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_probe_bolt_white.png"));
                    bridge.channelOcclusion = false; bridge.RefreshChannelOcclusion(); yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_probe_bolt_white_noocc.png"));
                    var fresh = new Material(shader) { hideFlags = HideFlags.DontSave }; pl.sharedMaterial = fresh; yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_probe_bolt_fresh.png"));
                    Object.DestroyImmediate(fresh); bridge.channelOcclusion = occ; bridge.RefreshChannelOcclusion();
                    var unlit = new Material(Shader.Find("HDRP/Unlit")) { hideFlags = HideFlags.DontSave }; unlit.SetColor("_UnlitColor", Color.white);
                    pl.sharedMaterial = unlit; pl.startColor = pl.endColor = Color.white;
                    yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_probe_unlit.png"));
                    Object.DestroyImmediate(probe); Object.DestroyImmediate(unlit);
                    bridge.channelOcclusion = false; bridge.RefreshChannelOcclusion(); yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_noocclusion.png"));
                    flashes.ChannelMaterial.SetColor("_Color", new Color(em * 30, em * 30, em * 30, 1)); yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_bright.png"));
                    flashes.minimumPixelWidth = 3; flashes.PrepareForCamera(cam); yield return null;
                    Save(cam, flashes, Path.Combine(ShotDir, "lightning_debug_wide.png"));
                    flashes.minimumPixelWidth = px; flashes.ChannelMaterial.SetColor("_Color", new Color(em, em, em, 1));
                    bridge.channelOcclusion = occ; bridge.RefreshChannelOcclusion();
                }
            }
            if (got < c.shots) { missing += c.shots - got; rep.AppendLine($"| {c.name} | {c.kind} | only {got} of {c.shots} flashes found a cloud anchor in {events.Count} candidates | | | | | | | | |"); }
        }
        flashes.ResetPlayback(); flashes.minimumPixelWidth = px0;
        rep.AppendLine();
        rep.AppendLine($"- {(missing == 0 ? "PASS" : "FAIL")}: a flash of every kind was made ({missing} missing)");
        rep.AppendLine($"- {(contactsOff == 0 ? "PASS" : "FAIL")}: every ground channel (the trunk and any fork to the ground) ends on the terrain ({contactsOff} off it)");
        rep.AppendLine($"- {(reachingOut == reachingTried ? "PASS" : "FAIL")}: the reaching bolts strike over 3 km out from where they began ({reachingOut} of {reachingTried})");
        rep.AppendLine($"- {(crawlersLow == 0 && crawlersShort == 0 ? "PASS" : "FAIL")}: crawlers stay over 2 km up ({crawlersLow} low) and spread over 6 km ({crawlersShort} short)");
        rep.AppendLine($"- {(crawlersAtOnce == 0 ? "PASS" : "FAIL")}: crawlers run out over half a second or more, most of their channels setting out after the trunk's leader ({crawlersAtOnce} appearing at once)");
        rep.AppendLine($"- {(branchesBusy == 0 ? "PASS" : "FAIL")}: ground bolts carry at most 14 side leaders, none over 3.5 km ({branchesBusy} busier)");
        ok &= missing == 0 && contactsOff == 0 && reachingOut == reachingTried && crawlersLow == 0 && crawlersShort == 0 && crawlersAtOnce == 0 && branchesBusy == 0;
        rep.AppendLine().AppendLine("Images: " + string.Join(", ", shots.Select(s => $"`Screenshots/{s}`")) + "; contact sheet `Screenshots/lightning_sheet.jpg`.");
        // contact sheet, two columns
        int cw = 800, ch2 = 450, rows = (shots.Count + 1) / 2;
        var sheet = new Texture2D(cw * 2, ch2 * rows, TextureFormat.RGB24, false);
        for (int i = 0; i < shots.Count; i++)
        {
            var tex = new Texture2D(2, 2); tex.LoadImage(File.ReadAllBytes(Path.Combine(ShotDir, shots[i])));
            var small = Scale(tex, cw, ch2);
            sheet.SetPixels((i % 2) * cw, (rows - 1 - i / 2) * ch2, cw, ch2, small);
            Object.DestroyImmediate(tex);
        }
        sheet.Apply();
        File.WriteAllBytes(Path.Combine(ShotDir, "lightning_sheet.jpg"), sheet.EncodeToJPG(88));
        Object.DestroyImmediate(sheet);
        sl.enabled = true;
    }

    static void Save(Camera camera, LightningSystem lightning, string path)
    {
        var rt = new RenderTexture(1600, 900, 24, RenderTextureFormat.ARGB32, RenderTextureReadWrite.sRGB);
        rt.Create();
        lightning.PrepareForCamera(camera);
        var request = new UnityEngine.Rendering.RenderPipeline.StandardRequest { destination = rt };
        if (UnityEngine.Rendering.RenderPipeline.SupportsRenderRequest(camera, request)) UnityEngine.Rendering.RenderPipeline.SubmitRenderRequest(camera, request);
        else { camera.targetTexture = rt; camera.Render(); camera.targetTexture = null; }
        var previous = RenderTexture.active; RenderTexture.active = rt;
        var image = new Texture2D(1600, 900, TextureFormat.RGB24, false);
        image.ReadPixels(new Rect(0, 0, 1600, 900), 0, 0); image.Apply();
        RenderTexture.active = previous;
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        File.WriteAllBytes(path, image.EncodeToPNG());
        Object.DestroyImmediate(image); rt.Release(); Object.DestroyImmediate(rt);
    }

    static Color[] Scale(Texture2D tex, int w, int h)
    {
        var px = new Color[w * h]; var src = tex.GetPixels();
        for (int y = 0; y < h; y++) for (int x = 0; x < w; x++)
            px[y * w + x] = src[Mathf.Min(tex.height - 1, y * tex.height / h) * tex.width + Mathf.Min(tex.width - 1, x * tex.width / w)];
        return px;
    }
}
