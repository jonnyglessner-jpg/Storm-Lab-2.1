// Play-mode check of the test map's sound (TestMapAudio). Enters Play with the scene as built, then:
//   1  wiring: the storm audio, ambience and truck audio exist, the ambience's calls are made, the mixer is running
//   2  truck: pushed along at speed the gearbox shifts up and the rpm rises; shoved sideways the tyres squeal
//   3  rain: dry well upwind of the storm; under the mature storm's forward-flank core, heavy
//   4  tornado: the storm paused with a tornado on the ground and the truck walked in toward it (its wind force off):
//      the wind sound grows as the wind does, is silent far off, and the birds fall silent when it starts
//   5  thunder: the storm running at 10x with the truck 6 km off: flashes are heard, nearer ones louder
// validation/reports/StormAudioCheck.md.
//   StormLab > Test Map > Storm Audio Check
// Batch: -executeMethod StormAudioCheck.RunFromCommandLine (never with -nographics)
using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using StormLab;
using StormLab.Audio;
using StormLab.Lightning;
using StormLab.TestMap;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using Object = UnityEngine.Object;

[InitializeOnLoad]
public static class StormAudioCheck
{
    const string Key = "StormAudioCheck.Active", BatchKey = "StormAudioCheck.Batch", CodeKey = "StormAudioCheck.Code";
    static string ReportPath => Path.Combine(StormLabTestKit.RepoRoot, "validation", "reports", "StormAudioCheck.md");

    static StormAudioCheck()
    {
        if (SessionState.GetBool(Key, false)) EditorApplication.playModeStateChanged += OnState;
    }

    [MenuItem("StormLab/Test Map/Storm Audio Check")]
    public static void RunMenu() => Begin(false);
    public static void RunFromCommandLine() => Begin(true);

    static void Begin(bool batch)
    {
        EditorSceneManager.OpenScene(TestMapBuilder.ScenePath, OpenSceneMode.Single);
        SessionState.SetBool(Key, true); SessionState.SetBool(BatchKey, batch);
        EditorApplication.playModeStateChanged -= OnState;
        EditorApplication.playModeStateChanged += OnState;
        EditorApplication.EnterPlaymode();
    }

    static void OnState(PlayModeStateChange s)
    {
        if (s == PlayModeStateChange.EnteredPlayMode)
        {
            errors = 0; errorLines.Clear(); rep.Clear(); ok = true;
            Application.logMessageReceived += OnLog;
            routine = Run().GetEnumerator();
            EditorApplication.update += Tick;
        }
        else if (s == PlayModeStateChange.EnteredEditMode && SessionState.GetBool(Key, false))
        {
            SessionState.SetBool(Key, false);
            EditorApplication.playModeStateChanged -= OnState;
            if (SessionState.GetBool(BatchKey, false)) EditorApplication.Exit(SessionState.GetInt(CodeKey, 1));
        }
    }

    static int errors; static readonly List<string> errorLines = new List<string>();
    static void OnLog(string msg, string stack, LogType t)
    {
        if (t != LogType.Error && t != LogType.Exception && t != LogType.Assert) return;
        if (stack != null && stack.Contains("UnityEditor.Search")) return;   // Unity's search indexer at start-up
        errors++; if (errorLines.Count < 12) errorLines.Add($"{t}: {msg.Split('\n')[0]}");
    }

    static readonly StringBuilder rep = new StringBuilder();
    static bool ok;
    static IEnumerator<object> routine;

    static void Tick()
    {
        if (!EditorApplication.isPlaying) return;
        bool more;
        try { more = routine.MoveNext(); }
        catch (Exception e) { Debug.LogException(e); ok = false; more = false; }
        if (more) return;
        EditorApplication.update -= Tick;
        Application.logMessageReceived -= OnLog;
        rep.AppendLine().AppendLine($"## Errors logged: {errors}").AppendLine();
        foreach (var l in errorLines) rep.AppendLine($"- {l}");
        ok &= errors == 0;
        rep.Insert(0, $"# Storm audio check: {(ok ? "PASS" : "FAIL")}\n\nGenerated by `StormAudioCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}, {SystemInfo.graphicsDeviceName}, Unity {Application.unityVersion}, batch {Application.isBatchMode}, output {AudioSettings.outputSampleRate} Hz.\n\n");
        Directory.CreateDirectory(Path.GetDirectoryName(ReportPath));
        File.WriteAllText(ReportPath, rep.ToString());
        Debug.Log($"[StormAudio] {(ok ? "PASS" : "FAIL")}; report {ReportPath}");
        SessionState.SetInt(CodeKey, ok ? 0 : 1);
        EditorApplication.ExitPlaymode();
    }

    static void Check(bool pass, string what) { ok &= pass; rep.AppendLine($"- {(pass ? "PASS" : "FAIL")}: {what}"); }
    static IEnumerable<object> Wait(float seconds) { float t0 = Time.realtimeSinceStartup; while (Time.realtimeSinceStartup - t0 < seconds) yield return null; }

    /// <summary>the mixer's output level now, dBFS (RMS of the last 4096 samples, both channels)</summary>
    static float OutputDb()
    {
        var a = new float[4096]; double e = 0;
        for (int c = 0; c < 2; c++) { AudioListener.GetOutputData(a, c); foreach (var x in a) e += x * x; }
        return 10f * Mathf.Log10((float)(e / 8192) + 1e-12f);
    }

    static Vector3 Ground(Vector3 p) => Physics.Raycast(p + Vector3.up * 3000f, Vector3.down, out var hit, 6000f) ? hit.point : new Vector3(p.x, 0f, p.z);

    static IEnumerable<object> Run()
    {
        foreach (var x in Wait(3f)) yield return x;
        var world = Object.FindAnyObjectByType<TestMapWorld>();
        var audio = world ? world.GetComponent<TestMapAudio>() : null;
        var storm = world ? world.storm : null;
        if (!world || !audio || !storm || !world.car) { Check(false, $"scene objects: world {world}, audio {audio}, storm {storm}"); yield break; }
        var sa = audio.Storm; var amb = audio.Ambience; var car = world.car; var carAudio = car.GetComponent<TestMapCarAudio>();
        var P = storm.Plan;

        // ---- 1 wiring
        rep.AppendLine("## 1 Wiring").AppendLine();
        Check(sa && amb && carAudio, "StormAudio, CountryAmbience and TestMapCarAudio are made at Start");
        double dsp0 = AudioSettings.dspTime;
        foreach (var x in Wait(1f)) yield return x;
        bool mixing = AudioSettings.dspTime > dsp0;
        Check(mixing, $"the audio mixer runs (dsp clock {dsp0:0.00} -> {AudioSettings.dspTime:0.00} s)");
        foreach (var x in Wait(2f)) yield return x;
        var voicesNow = "";
        foreach (var pa in Object.FindObjectsByType<ProceduralAudio>())
            voicesNow += $" {pa.name}: playing {pa.Source.isPlaying}, volume {pa.Source.volume:0.00}, {pa.Blocks} blocks;";
        rep.AppendLine($"- voices:{voicesNow} listener volume {AudioListener.volume}, paused {AudioListener.pause}, " +
                       $"{Object.FindObjectsByType<AudioListener>().Length} listener(s)");
        // (the first read of the output after Play comes back empty: take the loudest of a few)
        var trace = "- output dBFS each 0.5 s:"; float idleDb = -120f;
        for (int k = 0; k < 6; k++)
        {
            foreach (var x in Wait(0.5f)) yield return x;
            float db = OutputDb(); idleDb = Mathf.Max(idleDb, db); trace += $" {db:0}";
        }
        rep.AppendLine(trace);
        Check(idleDb > -80f, $"something is heard with the truck idling and the breeze ({idleDb:0.0} dBFS)");

        if (Array.IndexOf(System.Environment.GetCommandLineArgs(), "-slAudioWiring") >= 0) yield break;

        // ---- 2 truck
        rep.AppendLine().AppendLine("## 2 Truck").AppendLine();
        car.acceptInput = false; world.tornadoWind = false;
        var road = world.spots.Length > 0 ? world.spots[0] : new TestMapWorld.Spot { position = car.transform.position };
        car.Teleport(road.position, Quaternion.Euler(0f, road.heading, 0f));
        foreach (var x in Wait(1.5f)) yield return x;
        float idleRpm = carAudio.Gearbox.rpm;
        int maxGear = 0; float maxRpm = 0f;
        float t0 = Time.realtimeSinceStartup;
        while (Time.realtimeSinceStartup - t0 < 4f)
        {
            // pushed along the road at 30 m/s
            var rb = car.Body; var f = car.transform.forward;
            rb.linearVelocity = new Vector3(f.x * 30f, rb.linearVelocity.y, f.z * 30f);
            maxGear = Mathf.Max(maxGear, carAudio.Gearbox.gear); maxRpm = Mathf.Max(maxRpm, carAudio.Gearbox.rpm);
            yield return null;
        }
        Check(maxGear >= 3 && maxRpm > idleRpm + 300f, $"at 30 m/s the gearbox is in gear {maxGear + 1}, {maxRpm:0} rpm (idle {idleRpm:0})");
        float maxSkid = 0f; t0 = Time.realtimeSinceStartup;
        while (Time.realtimeSinceStartup - t0 < 1.5f)
        {
            // shoved sideways: the tyres slide
            var rb = car.Body; var r = car.transform.right; var f = car.transform.forward;
            rb.linearVelocity = f * 15f + r * 9f + Vector3.up * rb.linearVelocity.y;
            maxSkid = Mathf.Max(maxSkid, carAudio.Skid);
            yield return null;
        }
        Check(maxSkid > 0.3f, $"sliding sideways at 9 m/s the tyres squeal (skid {maxSkid:0.00})");
        car.Body.linearVelocity = Vector3.zero;

        // ---- 3 rain
        rep.AppendLine().AppendLine("## 3 Rain").AppendLine();
        float form = P.cycles != null ? (float)P.cycles[0].times[2] : 48f;
        storm.playing = false; storm.StormTime = form - 6f;
        foreach (var x in Wait(2f)) yield return x;
        var mv = new Vector3((float)P.motion.x, 0f, (float)P.motion.y).normalized;
        var up = storm.UpdraftWorld(storm.StormTime);
        car.Teleport(Ground(up - mv * 35000f), Quaternion.identity);
        foreach (var x in Wait(3f)) yield return x;
        float dryRain = sa.Rain;
        Check(dryRain < 0.03f, $"35 km upwind of the updraft it is dry (rain {dryRain:0.000})");
        var a = storm.Frame.param;
        var core = storm.StormToWorld(new Vector3(a[36], a[37], 0f));
        car.Teleport(Ground(core), Quaternion.identity);
        foreach (var x in Wait(3f)) yield return x;
        float coreRain = sa.Rain; float coreDb = OutputDb();
        Check(coreRain > 0.25f, $"under the forward-flank core ({a[39]:0.00} amount) it pours (rain {coreRain:0.00}, hail {sa.Hail:0.00}); output {coreDb:0.0} dBFS");
        // a walk out of the core: the rain eases
        var line = "- rain walking out of the core toward the inflow:";
        var outward = (core - up); outward.y = 0f; outward = -outward.normalized;
        foreach (float km in new[] { 0f, 4f, 8f, 14f, 22f })
        {
            car.Teleport(Ground(core + outward * km * 1000f), Quaternion.identity);
            foreach (var x in Wait(1.2f)) yield return x;
            line += $"  {km} km {sa.Rain:0.00}";
        }
        rep.AppendLine(line);

        // ---- 4 tornado
        rep.AppendLine().AppendLine("## 4 Tornado wind and birds").AppendLine();
        // the strongest moment of the first cycle that puts a tornado down
        double best = -1; float bestAmt = 0f;
        foreach (var c in P.cycles ?? new StormCycle[0])
        {
            for (double tm = c.times[2]; tm < c.times[2] + 8; tm += 1)
            {
                storm.StormTime = tm;
                foreach (var x in Wait(0.6f)) yield return x;
                if (storm.TornadoAmount > bestAmt) { bestAmt = storm.TornadoAmount; best = tm; }
            }
            if (bestAmt > 0.6f) break;
        }
        if (best >= 0) storm.StormTime = best;
        foreach (var x in Wait(1f)) yield return x;
        Check(storm.TornadoAmount > 0.3f, $"a tornado on the ground at {storm.stormMinutes:0.0} min (amount {storm.TornadoAmount:0.00})");
        var tor = storm.TornadoGroundWorld;
        car.Teleport(Ground(tor + Vector3.right * 15000f), Quaternion.identity);
        foreach (var x in Wait(2f)) yield return x;
        Check(sa.TornadoAudio < 0.005f && !amb.BirdsSilenced, $"15 km off: no wind sound ({sa.WindSpeed:0.0} m/s, level {sa.TornadoAudio:0.000}); birds singing");
        Check(sa.RoarLevel < 0.005f, $"15 km off: no roar either (level {sa.RoarLevel:0.000})");
        float prevLevel = -1f, maxWind = 0f, roarAtKm = 0f; bool rising = true; line = "- walking in (distance: wind m/s, wind sound 0..1, roar 0..1, output dBFS):";
        foreach (float m in new[] { 4000f, 2000f, 1000f, 500f, 250f, 120f, 60f, 35f })
        {
            car.Teleport(Ground(storm.TornadoGroundWorld + Vector3.right * m), Quaternion.identity);
            foreach (var x in Wait(2.5f)) yield return x;
            if (m == 1000f) roarAtKm = sa.RoarLevel;
            line += $"  {m:0} m: {sa.WindSpeed:0} / {sa.TornadoAudio:0.00} / {sa.RoarLevel:0.00} / {OutputDb():0}";
            // (inside the core the wind can drop again: compare with the wind, not the distance)
            if (sa.WindSpeed > maxWind) { if (sa.TornadoAudio < prevLevel - 0.02f) rising = false; maxWind = sa.WindSpeed; prevLevel = Mathf.Max(prevLevel, sa.TornadoAudio); }
        }
        rep.AppendLine(line);
        float expect = WindSynth.Intensity(maxWind, sa.windRange.x, sa.windRange.y);
        Check(rising && prevLevel > 0.05f && Mathf.Abs(prevLevel - expect) < 0.1f,
              $"the wind sound grows with the wind as the truck nears the tornado (tornado amount {storm.TornadoAmount:0.00}; to {prevLevel:0.00} at {maxWind:0} m/s, {maxWind * 2.237f:0} mph)");
        Check(roarAtKm > 0.1f, $"the roar is well heard a kilometre out (level {roarAtKm:0.00}, strength {sa.RoarStrength:0.00}; user 2026-10-30: loud a mile away)");
        Check(amb.BirdsSilenced, "the birds are silent once the tornado is heard");
        car.Teleport(Ground(storm.TornadoGroundWorld + Vector3.right * 15000f), Quaternion.identity);
        foreach (var x in Wait(2f)) yield return x;
        Check(amb.BirdsSilenced, $"and stay silent just after it is gone (they return {amb.birdsReturnAfter:0} s later)");

        // ---- 5 thunder
        rep.AppendLine().AppendLine("## 5 Thunder").AppendLine();
        sa.thunder = true;   // (whatever the switch was left at, the check tests it)
        int flashes = 0; var ls = storm.GetComponent<LightningSystem>();
        Action<LightningFlash> count = _ => flashes++;
        if (ls) ls.FlashStarted += count;
        storm.StormTime = form - 4f; storm.playing = true; storm.minutesPerSecond = 10f / 60f;
        up = storm.UpdraftWorld(storm.StormTime);
        car.Teleport(Ground(up + Quaternion.Euler(0, 110, 0) * mv * 6000f), Quaternion.identity);
        int played0 = sa.ThunderPlayed; var heard = new List<string>(); var levels = new List<(float near, float db)>();
        t0 = Time.realtimeSinceStartup; StormAudio.ThunderHeard last = null;
        rep.AppendLine($"- thunder from {sa.thunderSound}");
        while (Time.realtimeSinceStartup - t0 < 40f)
        {
            if (sa.LastThunder != last && sa.LastThunder != null)
            {
                last = sa.LastThunder;
                levels.Add((last.nearestM, last.levelDb));
                if (heard.Count < 12) heard.Add($"{last.nearestM / 1000f:0.0} km, delay {last.delaySeconds:0.0} s, {last.lengthSeconds:0} s long, level {last.levelDb:0} dBFS ({last.what})");
            }
            yield return null;
        }
        if (ls) ls.FlashStarted -= count;
        int played = sa.ThunderPlayed - played0;
        foreach (var h in heard) rep.AppendLine($"- heard: {h}");
        Check(flashes == 0 || played > 0, $"{flashes} flashes in 40 s, {played} thunder heard");
        if (levels.Count >= 6)
        {
            // the nearer half of the flashes heard is louder than the farther half
            levels.Sort((x, y) => x.near.CompareTo(y.near));
            int h = levels.Count / 2; float nearDb = 0f, farDb = 0f; float nearKm = 0f, farKm = 0f;
            for (int i = 0; i < h; i++) { nearDb += levels[i].db / h; nearKm += levels[i].near / 1000f / h; }
            for (int i = levels.Count - h; i < levels.Count; i++) { farDb += levels[i].db / h; farKm += levels[i].near / 1000f / h; }
            Check(nearDb > farDb + 1f, $"nearer thunder is louder: nearer half (mean {nearKm:0.0} km) {nearDb:0.0} dBFS RMS, farther half ({farKm:0.0} km) {farDb:0.0} dBFS");
        }
        storm.playing = false;
    }
}
