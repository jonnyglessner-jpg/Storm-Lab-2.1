// Check of the test map's GPS and radar map (TestMapMinimap, TestMapRoads, StormRadar). Routes: the network is one
// piece, and 300 random trips find a route that starts and ends where asked, never jumps, and is not much longer than
// the trip by the section grid; one trip's directions are listed. Radar: in Play, the test storm at its first tornado,
// the truck 14 km off; the base and composite scans are read back (the most reflectivity, how much ground at 20, 40, 50
// and 60 dBZ, the reflectivity at the hail core, the forward-flank core and the tornado) and the map is drawn over the
// chaser's view in the corner and full screen, with a route to the storm (Screenshots/minimap_*.png).
//   StormLab > Test Map > Map and Radar Check
// Batch: -executeMethod TestMapMinimapCheck.RunFromCommandLine (never with -nographics)
