    static void Begin(bool batch)
    {
        EditorSceneManager.OpenScene(TestMapBuilder.ScenePath, OpenSceneMode.Single);
        SessionState.SetBool(Key, true); SessionState.SetBool(BatchKey, batch);
        EditorApplication.playModeStateChanged -= OnState;
        EditorApplication.playModeStateChanged += OnState;
        EditorApplication.EnterPlaymode();
    }

    static IEnumerator<object> routine; static readonly StringBuilder rep = new StringBuilder(); static bool ok; static int errors;
    static readonly List<string> errorLines = new List<string>();

    static void OnState(PlayModeStateChange s)
    {
        if (s == PlayModeStateChange.EnteredPlayMode)
        {
            rep.Clear(); ok = true; errors = 0; errorLines.Clear();
            Application.logMessageReceived += OnLog;
            routine = Run().GetEnumerator();
            EditorApplication.update += Tick;
        }
        else if (s == PlayModeStateChange.EnteredEditMode && SessionState.GetBool(Key, false))
        {
            SessionState.SetBool(Key, false);
            EditorApplication.playModeStateChanged -= OnState;
            if (SessionState.GetBool(BatchKey, false)) EditorApplication.Exit(SessionState.GetInt(CodeKey, 1));
        }
    }

    static void OnLog(string msg, string stack, LogType t)
    {
        if (t != LogType.Error && t != LogType.Exception && t != LogType.Assert) return;
        if (stack != null && stack.Contains("UnityEditor.Search")) return;
        errors++; if (errorLines.Count < 10) errorLines.Add($"{t}: {msg.Split('\n')[0]}");
    }

    static void Tick()
    {
        if (!EditorApplication.isPlaying) return;
        bool more;
        try { more = routine.MoveNext(); }
        catch (Exception e) { Debug.LogException(e); ok = false; more = false; }
        if (more) return;
        EditorApplication.update -= Tick;
        Application.logMessageReceived -= OnLog;
        rep.AppendLine().AppendLine($"Errors logged: {errors}");
        foreach (var l in errorLines) rep.AppendLine($"- {l}");
        ok &= errors == 0;
        rep.Insert(0, $"# Map and radar check: {(ok ? "PASS" : "FAIL")}\n\nGenerated by `TestMapMinimapCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}, {SystemInfo.graphicsDeviceName}.\n\n");
        Directory.CreateDirectory(Path.GetDirectoryName(ReportPath));
        File.WriteAllText(ReportPath, rep.ToString());
        Debug.Log($"[MinimapCheck] {(ok ? "PASS" : "FAIL")}; report {ReportPath}");
        SessionState.SetInt(CodeKey, ok ? 0 : 1);
        EditorApplication.ExitPlaymode();
    }

    static IEnumerable<object> Frames(int n) { for (int i = 0; i < n; i++) yield return null; }
    // Player frames, not editor ticks: EditorApplication.update runs far more often than the game renders, so a scan
    // asked for (StormRadar.ScanAll) is only drawn once the game has rendered a frame or two since
    static IEnumerable<object> PlayerFrames(int n) { int f0 = Time.frameCount; while (Time.frameCount < f0 + n) yield return null; }

    static void Check(bool pass, string what) { ok &= pass; rep.AppendLine($"- {(pass ? "pass" : "**FAIL**")}: {what}"); }

    // ------------------------------------------------------------------ routes
    static void Routes(TestMapRoads roads)
    {
        rep.AppendLine("## Routes").AppendLine();
        // one piece: every junction with a road reaches every other
        var seen = new bool[roads.nodes.Length]; var stack = new Stack<int>();
        int start = roads.edges[0].a; stack.Push(start); seen[start] = true; int reached = 1;
        while (stack.Count > 0) foreach (int e in roads.adj[stack.Pop()]) { var ed = roads.edges[e]; foreach (int v in new[] { ed.a, ed.b }) if (!seen[v]) { seen[v] = true; reached++; stack.Push(v); } }
        int withRoads = Enumerable.Range(0, roads.nodes.Length).Count(i => roads.adj[i].Count > 0);
        Check(reached == withRoads, $"the network is one piece ({reached} of {withRoads} junctions and corners reached, {roads.edges.Length} road pieces)");

        // the longest straight stretch between two points of the network: no step of a route may be longer
        float longest = 0f;
        foreach (var ed in roads.edges) for (int k = 1; k < ed.pts.Length; k++) longest = Mathf.Max(longest, Vector2.Distance(ed.pts[k - 1], ed.pts[k]));
        var rnd = new System.Random(2026);
        float half = roads.sizeM / 2 - 500f;
        int found = 0, trips = 300, jumps = 0, badEnds = 0; var ratios = new List<float>(); double ms = 0;
        TestMapRoads.Route sample = null;
        for (int i = 0; i < trips; i++)
        {
            var a = new Vector2((float)(rnd.NextDouble() * 2 - 1) * half, (float)(rnd.NextDouble() * 2 - 1) * half);
            var b = new Vector2((float)(rnd.NextDouble() * 2 - 1) * half, (float)(rnd.NextDouble() * 2 - 1) * half);
            var heading = new Vector2((float)rnd.NextDouble() - 0.5f, (float)rnd.NextDouble() - 0.5f).normalized;
            var sw = System.Diagnostics.Stopwatch.StartNew();
            var from = roads.Nearest(a, heading); var to = roads.Nearest(b);
            var r = roads.Plan(from, to, heading);
            ms += sw.Elapsed.TotalMilliseconds;
            if (r == null) continue;
            found++;
            for (int k = 1; k < r.pts.Count; k++) if (Vector2.Distance(r.pts[k - 1], r.pts[k]) > longest + 1f) { jumps++; break; }
            if (Vector2.Distance(r.pts[0], from.point) > 1f || Vector2.Distance(r.pts[r.pts.Count - 1], to.point) > 1f) badEnds++;
            // against the trip along the section grid (east-west plus north-south)
            float grid = Mathf.Abs(to.point.x - from.point.x) + Mathf.Abs(to.point.y - from.point.y);
            if (grid > 3000f) ratios.Add(r.Length / grid);
            if (sample == null && grid > 25000f && r.steps.Count >= 4) sample = r;
        }
        Check(found == trips, $"{found} of {trips} random trips found a route ({ms / trips:0.0} ms each, nearest-road search included)");
        Check(jumps == 0 && badEnds == 0, $"routes are continuous ({jumps} with a step longer than the network's longest straight, {longest:0} m) and start and end where asked ({badEnds} not)");
        ratios.Sort();
        Check(ratios.Count > 0 && ratios[ratios.Count - 1] < 1.6f, $"route length over the grid distance: median {ratios[ratios.Count / 2]:0.00}, longest {ratios[ratios.Count - 1]:0.00} (rivers are bridged only every few miles)");
        if (sample != null)
        {
            rep.AppendLine().AppendLine($"A sample trip: {TestMapRoads.Distance(sample.Length)}, {sample.Seconds / 60f:0} min:").AppendLine();
            foreach (var s in sample.steps) rep.AppendLine($"    {TestMapRoads.Distance(s.at),8}  {TestMapRoads.Say(s.turn, s.road)}");
        }
        rep.AppendLine();
    }

    // ------------------------------------------------------------------ radar
    static float[] ReadDbz(StormRadar radar)
    {
        var req = AsyncGPUReadback.Request(radar.Dbz, 0, TextureFormat.RHalf);
        req.WaitForCompletion();
        if (req.hasError) return null;
        return req.GetData<ushort>().Select(Mathf.HalfToFloat).ToArray();
    }

    // what the scan's reflectivity factor holds: zeros, NaN or infinities, values, and the largest
    static string RawZ(StormRadar radar)
    {
        if (!radar.ReflectivityFactor) return "no Z texture";
        var req = AsyncGPUReadback.Request(radar.ReflectivityFactor, 0, TextureFormat.RFloat);
        req.WaitForCompletion();
        if (req.hasError) return "Z readback failed";
        var v = req.GetData<float>();
        int zero = 0, bad = 0, pos = 0; float most = 0f;
        foreach (var f in v) { if (float.IsNaN(f) || float.IsInfinity(f)) bad++; else if (f <= 0f) zero++; else { pos++; most = Mathf.Max(most, f); } }
        return $"raw Z: {pos} texels with echo (most {most:0.##E+0}), {zero} zero, {bad} NaN or infinite";
    }

    static float DbzAt(StormRadar radar, float[] d, Vector3 w, float radiusM)
    {
        var a = radar.Area; int n = radar.Dbz.width; float best = -99f;
        int r = Mathf.CeilToInt(radiusM / (a.width / n));
        int cx = Mathf.FloorToInt((w.x - a.xMin) / a.width * n), cy = Mathf.FloorToInt((w.z - a.yMin) / a.height * n);
        for (int y = cy - r; y <= cy + r; y++) for (int x = cx - r; x <= cx + r; x++)
            if (x >= 0 && y >= 0 && x < n && y < n) best = Mathf.Max(best, d[y * n + x]);
        return best;
    }

    static string Stats(StormRadar radar, float[] d)
    {
        float cell = radar.Area.width / radar.Dbz.width; float km2 = cell * cell / 1e6f;
        string Area(float t) => $"{d.Count(v => v >= t) * km2:0} km²";
        return $"most {d.Max():0} dBZ; at 20+ dBZ {Area(20)}, 40+ {Area(40)}, 50+ {Area(50)}, 60+ {Area(60)}";
    }

    static void Shot(Camera cam, TestMapMinimap map, string name, bool full, bool scene)
    {
        const int W = 1600, H = 900;
        var rt = new RenderTexture(W, H, 24, RenderTextureFormat.ARGB32, RenderTextureReadWrite.sRGB) { antiAliasing = 1 };
        rt.Create();
        if (scene)
        {
            for (int f = 0; f < 6; f++)
            {
                var req = new RenderPipeline.StandardRequest { destination = rt };
                if (RenderPipeline.SupportsRenderRequest(cam, req)) RenderPipeline.SubmitRenderRequest(cam, req);
                else { cam.targetTexture = rt; cam.Render(); cam.targetTexture = null; }
            }
        }
        map.RenderMap(rt, full);
        var prev = RenderTexture.active; RenderTexture.active = rt;
        var tex = new Texture2D(W, H, TextureFormat.RGB24, false);
        tex.ReadPixels(new Rect(0, 0, W, H), 0, 0); tex.Apply();
        RenderTexture.active = prev;
        Directory.CreateDirectory(ShotDir);
        File.WriteAllBytes(Path.Combine(ShotDir, $"minimap_{name}.png"), tex.EncodeToPNG());
        Object.DestroyImmediate(tex); rt.Release(); Object.DestroyImmediate(rt);
        rep.AppendLine($"- `Screenshots/minimap_{name}.png`");
    }

    static IEnumerable<object> Run()
    {
        foreach (var x in Frames(30)) yield return x;
        var world = Object.FindAnyObjectByType<TestMapWorld>();
        var map = world ? world.GetComponent<TestMapMinimap>() : null;
        var storm = world ? world.storm : null;
        var cam = Camera.main;
        if (!map || !storm || !cam || map.Roads == null || !map.radar) { ok = false; rep.AppendLine($"FAIL: map {map}, storm {storm}, camera {cam}, roads {map?.Roads != null}, radar {map?.radar}"); yield break; }
        Routes(map.Roads);

        // the storm at its first tornado (or its first mature cycle), held there
        var rig = cam.GetComponent<TestMapCamera>(); if (rig) rig.enabled = false;
        var sl = storm.GetComponent<StormLightning>(); if (sl && sl.Flashes) { sl.Flashes.enabled = false; sl.Bridge.enabled = false; }
        storm.playing = false;
        var P = storm.Plan;
        float t = P.cycles != null ? (float)P.cycles[0].times[3] : 50f;
        storm.StormTime = t;
        world.PlaceStorm();
        storm.StepTo(t, storm.Clock, true);
        foreach (var x in Frames(10)) yield return x;
        var u = storm.UpdraftWorld(t);
        var radar = map.radar;
        rep.AppendLine("## Radar").AppendLine();
        rep.AppendLine($"Storm: {storm.preset} seed {storm.seed} at {t:0.0} min ({storm.Frame.stage}), updraft {Vector3.Distance(new Vector3(u.x, 0, u.z), new Vector3(radar.site.x, 0, radar.site.z)) / 1000f:0} km from {radar.siteName}; " +
                       $"tornado {(storm.TornadoAmount > 0.15f ? "on the ground" : "not down")}.").AppendLine();

        // the truck 14 km off the updraft, square to the storm's motion, on a road, facing it
        var mv = new Vector3((float)P.motion.x, 0, (float)P.motion.y).normalized;
        var off = new Vector3(u.x, 0, u.z) + Quaternion.Euler(0, 110, 0) * mv * 14000f;
        var spot = map.Roads.Nearest(new Vector2(off.x, off.z));
        var truckAt = new Vector3(spot.point.x, 0, spot.point.y);
        truckAt.y = Physics.Raycast(truckAt + Vector3.up * 3000f, Vector3.down, out var hit, 6000f) ? hit.point.y + 0.5f : 2f;
        var look = new Vector3(u.x, truckAt.y, u.z) - truckAt;
        world.car.Teleport(truckAt, Quaternion.LookRotation(look.normalized, Vector3.up));
        foreach (var x in Frames(5)) yield return x;
        map.SetDestination(new Vector2(u.x, u.z) - new Vector2(mv.x, mv.z) * 6000f);
        Check(map.Route != null, $"a route from the truck toward the storm: {(map.Route != null ? $"{TestMapRoads.Distance(map.Route.Length)}, {map.Route.steps.Count} steps, first: {TestMapRoads.Say(map.Route.steps[Mathf.Min(1, map.Route.steps.Count - 1)].turn, map.Route.steps[Mathf.Min(1, map.Route.steps.Count - 1)].road)}" : "none")}");

        var products = new[] { RadarProduct.BaseReflectivity, RadarProduct.CompositeReflectivity };
        var most = new Dictionary<RadarProduct, float>();
        foreach (var pr in products)
        {
            radar.product = pr; radar.ScanAll();
            storm.StepTo(t, storm.Clock, true);
            foreach (var x in PlayerFrames(3)) yield return x;
            var d = ReadDbz(radar);
            rep.AppendLine($"- {pr}: the sweep read {radar.StormsScanned} storm(s); {StormRenderer.Enabled.Count} enabled, storm ready {storm.ReadyToRender}; {RawZ(radar)}");
            if (d == null) { Check(false, "radar readback"); continue; }
            most[pr] = d.Max();
            var a = storm.Frame.param;
            var hail = storm.StormToWorld(new Vector3(a[40], a[41], 0));
            var ffd = storm.StormToWorld(new Vector3(a[36], a[37], 0));
            string tor = storm.TornadoAmount > 0.15f ? $", tornado (debris ball) {DbzAt(radar, d, storm.TornadoGroundWorld, 500f):0}" : "";
            if (pr == RadarProduct.BaseReflectivity)
            {
                var tg = storm.TornadoGroundWorld;
                rep.AppendLine($"- the storm frame: hail core {a[42]:0.0} km radius, amount {a[43]:0.00}; forward-flank core size {a[38]:0.00}, amount {a[39]:0.00}; " +
                               $"tornado {(tg - u).x / 1000f:0.0} km E, {(tg - u).z / 1000f:0.0} km N of the updraft, hail core {(hail - u).x / 1000f:0.0} E, {(hail - u).z / 1000f:0.0} N");
            }
            rep.AppendLine($"- {pr}: {Stats(radar, d)}; hail core {DbzAt(radar, d, hail, 1500f):0}, forward-flank core {DbzAt(radar, d, ffd, 2000f):0}{tor} dBZ (most within 1.5-2 km)");
        }
        Check(most.TryGetValue(RadarProduct.BaseReflectivity, out var mb) && mb > 50f && mb < 78f, $"base reflectivity peaks at a supercell's 50-75 dBZ ({mb:0})");
        Check(most.TryGetValue(RadarProduct.CompositeReflectivity, out var mc) && mc >= mb - 0.5f, $"composite reflectivity at least the base ({mc:0} against {mb:0})");
        rep.AppendLine().AppendLine("Pictures:").AppendLine();

        radar.product = RadarProduct.BaseReflectivity; radar.ScanAll();
        storm.StepTo(t, storm.Clock, true);
        foreach (var x in PlayerFrames(3)) yield return x;
        cam.transform.SetPositionAndRotation(truckAt + Vector3.up * 2f - look.normalized * 8f, Quaternion.LookRotation(new Vector3(u.x, truckAt.y + 1500f, u.z) - truckAt, Vector3.up));
        storm.ResetHistory(cam);
        Shot(cam, map, "corner", false, true);
        map.showStormMarkers = true;
        map.fullSpan = 60000f; map.CentreOn(new Vector2(u.x, u.z));
        Shot(cam, map, "full", true, false);
        map.fullSpan = 22000f;
        Shot(cam, map, "hook", true, false);
        radar.product = RadarProduct.CompositeReflectivity; radar.ScanAll();
        foreach (var x in PlayerFrames(3)) yield return x;
        Shot(cam, map, "hook_composite", true, false);
        radar.product = RadarProduct.BaseReflectivity;

        // ---- through the storm's life, and another setup: the features of a supercell on radar (user's references,
        // 2026-10-27): the inflow notch under the updraft, the hook behind the mesocyclone, the debris ball
        rep.AppendLine().AppendLine("## Through a storm's life").AppendLine();
        rep.AppendLine("| storm | time | stage | most | 50+ dBZ | inflow notch (rain-free base) | hook (most behind the wall cloud) | debris ball | picture |").AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
        var cases = new List<(string preset, string label, Func<StormPlan, float> at)>
        {
            ("plains", "first_echo", p => (float)p.cycles[0].start - 14f),
            ("plains", "organising", p => (float)p.cycles[0].start - 4f),
            ("plains", "tornado", p => (float)p.cycles[0].times[3]),
            ("plains", "later_cycle", p => (float)p.cycles[p.cycles.Length - 1].times[3]),
            ("dixie", "dixie_tornado", p => (float)p.cycles[0].times[3]),
        };
        foreach (var c in cases)
        {
            if (storm.preset != c.preset) { storm.preset = c.preset; storm.Replan(); world.PlaceStorm(); }
            var pl = storm.Plan;
            if (pl.cycles == null || pl.cycles.Length == 0) { rep.AppendLine($"| {c.preset} | - | no cycles | | | | | | |"); continue; }
            float tc = Mathf.Clamp(c.at(pl), 1f, (float)pl.duration - 1f);
            storm.StormTime = tc;
            storm.StepTo(tc, storm.Clock, true);
            radar.ScanAll();
            foreach (var x in PlayerFrames(3)) yield return x;
            var d = ReadDbz(radar);
            if (d == null) { Check(false, "radar readback"); continue; }
            var uc = storm.UpdraftWorld(tc);
            // the inflow notch: under the rain-free base, forward and right of the updraft (StormTilt; at the updraft
            // itself the tornado and its debris ball sit within half a km)
            var fa = storm.Frame.param; float baseR = storm.ClearParams.x;
            var nc = new Vector2(fa[16 * 4], fa[16 * 4 + 1]) + (new Vector2(fa[0], fa[1]) - new Vector2(fa[2], fa[3])) * 0.42f * Mathf.Max(baseR, 1.5f);
            float notch = DbzAt(radar, d, storm.StormToWorld(new Vector3(nc.x, nc.y, 0f)), 300f), hook = HookDbz(storm, radar, d);
            float debris = storm.TornadoAmount > 0.15f ? DbzAt(radar, d, storm.TornadoGroundWorld, 400f) : float.NaN;
            float cell = radar.Area.width / radar.Dbz.width;
            map.fullSpan = 30000f; map.CentreOn(new Vector2(uc.x, uc.z));
            Shot(cam, map, $"life_{c.label}", true, false);
            rep.AppendLine($"| {c.preset} seed {storm.seed} | {tc:0} min | {storm.Frame.stage} | {d.Max():0} | {d.Count(v => v >= 50f) * cell * cell / 1e6f:0} km² | {notch:0} | {hook:0} | {(float.IsNaN(debris) ? "-" : debris.ToString("0"))} | `minimap_life_{c.label}.png` |");
            if (c.label == "tornado" || c.label == "dixie_tornado")
            {
                // a classic storm keeps heavy rain out of its inflow notch (light rain and speckle may show); an HP storm's
                // rain wraps round the mesocyclone and through it (the bear's cage), so it is only reported
                if (storm.Plan.hpness < 0.5) Check(notch < 35f, $"{c.label}: no heavy rain in the inflow notch under the rain-free base ({notch:0} dBZ)");
                else rep.AppendLine($"- {c.label}: HP, its rain wraps through the inflow notch ({notch:0} dBZ there)");
                Check(hook > 40f, $"{c.label}: a hook behind the mesocyclone ({hook:0} dBZ)");
                Check(float.IsNaN(debris) || debris >= 45f, $"{c.label}: a debris ball at the tornado ({debris:0} dBZ)");
            }
        }
        // ---- the tilted updraft seen from the ground (StormTilt): the chaser's view of the base, wall cloud and rain, 8 km
        // off the storm's right flank, with the web build's rain and with the tilted updraft's, for each setup's first tornado
        rep.AppendLine().AppendLine("## The tilted updraft from the ground").AppendLine();
        foreach (var key in new[] { "plains", "dixie" })
        {
            storm.preset = key; storm.Replan(); world.PlaceStorm();
            var pl = storm.Plan;
            float tt = pl.cycles != null ? (float)pl.cycles[0].times[3] : 50f;
            var mvt = new Vector3((float)pl.motion.x, 0, (float)pl.motion.y).normalized;
            foreach (var layout in new[] { PrecipLayout.Website, PrecipLayout.Tilted })
            foreach (var km in new[] { 8, 4 })
            {
                storm.precip = layout;
                storm.StormTime = tt;
                storm.StepTo(tt, storm.Clock, true);
                var ut = storm.UpdraftWorld(tt);
                var tgt = storm.TornadoAmount > 0.15f ? storm.TornadoGroundWorld : new Vector3(ut.x, 0, ut.z);
                var from = tgt + Quaternion.Euler(0, 100, 0) * mvt * (km * 1000f);
                from.y = Physics.Raycast(from + Vector3.up * 3000f, Vector3.down, out var gh, 6000f) ? gh.point.y + 2f : 2f;
                cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(new Vector3(tgt.x, from.y + 110f * km, tgt.z) - from, Vector3.up));
                storm.ResetHistory(cam);
                foreach (var x in PlayerFrames(3)) yield return x;
                string name = $"tilt_{key}_{layout.ToString().ToLowerInvariant()}_{km}km";
                StormLabTestKit.Render(cam, Path.Combine(ShotDir, name + ".png"), 1600, 900, 6);
                var cp = storm.ClearParams;
                if (key == "dixie" && km == 4)
                {
                    // the same view with no rain at all: what of its outline is the cloud's, and what the rain's
                    storm.hideRain = true;
                    storm.StepTo(tt, storm.Clock, true);
                    storm.ResetHistory(cam);
                    foreach (var x in PlayerFrames(3)) yield return x;
                    StormLabTestKit.Render(cam, Path.Combine(ShotDir, name + "_norain.png"), 1600, 900, 6);
                    storm.hideRain = false;
                    storm.StepTo(tt, storm.Clock, true);
                    rep.AppendLine($"- {key} {layout}: `Screenshots/{name}_norain.png` (no rain: the cloud alone)");
                }
                rep.AppendLine($"- {key} {layout}: `Screenshots/{name}.png` (slope {(layout == PrecipLayout.Tilted ? StormTilt.Slope(pl) : Math.Sqrt(pl.tilt.x * pl.tilt.x + pl.tilt.y * pl.tilt.y)):0.00}, rain-free base {cp.x:0.0} km, tornado clear {cp.y:0.00} km)");
            }
        }
        storm.precip = PrecipLayout.Tilted;
        storm.preset = "plains"; storm.Replan();
    }

    /// <summary>The most reflectivity on the arc behind and right of the wall cloud (where the hook wraps), 1.2-3.5 km out.</summary>
    static float HookDbz(StormRenderer s, StormRadar radar, float[] d)
    {
        var a = s.Frame.param;
        Vector2 fw = new Vector2(a[0], a[1]), lf = new Vector2(a[2], a[3]), c = new Vector2(a[24], a[25]);
        float best = -99f;
        for (float phi = 150f; phi <= 300f; phi += 10f)
            for (float r = 1.2f; r <= 3.5f; r += 0.4f)
            {
                var q = c + (fw * Mathf.Cos(phi * Mathf.Deg2Rad) + lf * Mathf.Sin(phi * Mathf.Deg2Rad)) * r;
                best = Mathf.Max(best, DbzAt(radar, d, s.StormToWorld(new Vector3(q.x, q.y, 0f)), 1f));
            }
        return best;
    }
