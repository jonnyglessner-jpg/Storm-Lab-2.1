// Play-mode check of the cloud detail switch (StormRenderer.cloudDetail) on the plains test map: fixed views of one storm,
// paused, each drawn with the website's detail and with the enhanced detail, in the game's look. For each view: the
// march's GPU time at 1080p (the game's half-resolution march), the fine-detail energy of each image (mean absolute
// Laplacian of luminance: more is crisper), and a sheet with both frames above and a 1:1 crop of the centre of each below.
// Before the switch existed it drew the views as they were ("base", twice, for the noise floor of two identical runs).
// Screenshots/detail_*.png, validation/reports/CloudDetailCheck.md.
//   StormLab > Test Map > Cloud Detail Check
// Batch: -executeMethod CloudDetailCheck.RunFromCommandLine (never with -nographics)
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using StormLab;
using StormLab.Lightning;
using StormLab.TestMap;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;
using Object = UnityEngine.Object;

[InitializeOnLoad]
public static class CloudDetailCheck
{
    const string Key = "CloudDetailCheck.Active", BatchKey = "CloudDetailCheck.Batch", CodeKey = "CloudDetailCheck.Code";
    static string ShotDir => Path.Combine(StormLabTestKit.ProjectDir, "Screenshots");
    static string ReportDir => Path.Combine(StormLabTestKit.RepoRoot, "validation", "reports");

    static CloudDetailCheck() { if (SessionState.GetBool(Key, false)) EditorApplication.playModeStateChanged += OnState; }

    [MenuItem("StormLab/Test Map/Cloud Detail Check")]
    public static void RunMenu() => Begin(false);
    public static void RunFromCommandLine() => Begin(true);

    static void Begin(bool batch)
    {
        EditorSceneManager.OpenScene(TestMapBuilder.ScenePath, OpenSceneMode.Single);
        SessionState.SetBool(Key, true); SessionState.SetBool(BatchKey, batch);
        EditorApplication.playModeStateChanged -= OnState;
        EditorApplication.playModeStateChanged += OnState;
        EditorApplication.EnterPlaymode();
    }

    static void OnState(PlayModeStateChange s)
    {
        if (s == PlayModeStateChange.EnteredPlayMode)
        {
            errors = 0; errorLines.Clear(); rep.Clear(); ok = true;
            Application.logMessageReceived += OnLog;
            routine = Run().GetEnumerator();
            EditorApplication.update += Tick;
        }
        else if (s == PlayModeStateChange.EnteredEditMode && SessionState.GetBool(Key, false))
        {
            SessionState.SetBool(Key, false);
            EditorApplication.playModeStateChanged -= OnState;
            if (SessionState.GetBool(BatchKey, false)) EditorApplication.Exit(SessionState.GetInt(CodeKey, 1));
        }
    }

    static int errors; static readonly List<string> errorLines = new List<string>();
    static void OnLog(string msg, string stack, LogType t)
    {
        if (t != LogType.Error && t != LogType.Exception && t != LogType.Assert) return;
        if (stack != null && stack.Contains("UnityEditor.Search")) return;   // Unity's search indexer at start-up, not StormLab's
        errors++; if (errorLines.Count < 12) errorLines.Add($"{t}: {msg.Split('\n')[0]}");
    }

    static readonly StringBuilder rep = new StringBuilder();
    static bool ok; static IEnumerator<object> routine; static string reportName = "CloudDetailCheck";

    static void Tick()
    {
        if (!EditorApplication.isPlaying) return;
        bool more;
        try { more = routine.MoveNext(); }
        catch (Exception e) { Debug.LogException(e); ok = false; more = false; }
        if (more) return;
        EditorApplication.update -= Tick;
        Application.logMessageReceived -= OnLog;
        rep.AppendLine().AppendLine($"Errors logged: {errors}");
        foreach (var l in errorLines) rep.AppendLine($"- {l}");
        ok &= errors == 0;
        rep.Insert(0, $"# Cloud detail check: {(ok ? "PASS" : "FAIL")}\n\nGenerated by `CloudDetailCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}, {SystemInfo.graphicsDeviceName}.\n\n");
        Directory.CreateDirectory(ReportDir);
        File.WriteAllText(Path.Combine(ReportDir, reportName + ".md"), rep.ToString());
        Debug.Log($"[CloudDetail] {(ok ? "PASS" : "FAIL")}");
        SessionState.SetInt(CodeKey, ok ? 0 : 1);
        EditorApplication.ExitPlaymode();
    }

    static void Check(bool pass, string what) { ok &= pass; rep.AppendLine($"- {(pass ? "PASS" : "FAIL")}: {what}"); }
    static IEnumerable<object> Wait(float seconds) { float t0 = Time.realtimeSinceStartup; while (Time.realtimeSinceStartup - t0 < seconds) yield return null; }

    struct View { public string name, what; public float min, km, sideDeg, aimKm; }

    static IEnumerable<object> Run()
    {
        foreach (var x in Wait(2f)) yield return x;
        var world = Object.FindAnyObjectByType<TestMapWorld>();
        var storm = world ? world.storm : null;
        var sl = storm ? storm.GetComponent<StormLightning>() : null;
        var cam = Camera.main;
        if (!world || !storm || !cam) { Check(false, $"scene objects: world {world}, storm {storm}, camera {cam}"); yield break; }
        var rig = cam.GetComponent<TestMapCamera>(); if (rig) rig.enabled = false;
        if (sl) sl.Flashes.enabled = false;
        storm.performance = StormPerformance.Custom;
        storm.playing = false; storm.renderScale = 0.5f; storm.checkerboard = false;

        // the switch, if this build has it (a run from before it existed draws the views as they were)
        var field = typeof(StormRenderer).GetField("cloudDetail");
        string[] modes = field != null ? new[] { "Website", "Enhanced" } : new[] { "base", "base2" };
        void SetMode(string m) { if (field != null) field.SetValue(storm, Enum.Parse(field.FieldType, m)); }
        if (field == null) reportName = "CloudDetailCheck_before";

        var P = storm.Plan;
        float form = P.cycles != null ? (float)P.cycles[0].times[2] : 48f;
        // views by storm time, distance from the updraft (km), bearing from the sun's side (0: the sun behind the camera,
        // 90: lit from the side), and the height looked at (km)
        var views = new[]
        {
            new View { name = "cumulus_6km", what = "young cumulonimbus, sun behind the camera", min = 16f, km = 6f, sideDeg = 0f, aimKm = 4f },
            new View { name = "cumulus_4km", what = "young cumulonimbus close, sun behind the camera", min = 16f, km = 4f, sideDeg = 10f, aimKm = 3.5f },
            new View { name = "tower_side_14km", what = "updraft tower lit from the side", min = form - 6f, km = 14f, sideDeg = -80f, aimKm = 6f },
            new View { name = "base_8km", what = "the chaser's view of the base, 8 km", min = form, km = 8f, sideDeg = 40f, aimKm = 1.2f },
            new View { name = "wallcloud_3km", what = "wall cloud from 3 km", min = form, km = 3f, sideDeg = 60f, aimKm = 0.8f },
            new View { name = "far_25km", what = "the whole storm from 25 km", min = form - 6f, km = 25f, sideDeg = 20f, aimKm = 7f },
        };
        rep.AppendLine($"Storm: {storm.preset}, seed {storm.seed}, {P.kind}; first tornado forms at {form:0.0} min. Lighting {storm.lighting}, march at half resolution. Modes: {string.Join(", ", modes)}.").AppendLine();
        rep.AppendLine("| view | storm min | stage | mode | march 1080p (GPU) | detail energy |").AppendLine("| --- | --- | --- | --- | --- | --- |");

        double SyncMs() { var sw = System.Diagnostics.Stopwatch.StartNew(); StormLabTestKit.Sync(); return sw.Elapsed.TotalMilliseconds; }
        double Timed(int reps, Action<CommandBuffer> record)
        {
            using (var warm = new CommandBuffer()) { record(warm); Graphics.ExecuteCommandBuffer(warm); }
            StormLabTestKit.Sync();
            double idle = Enumerable.Range(0, 5).Select(_ => SyncMs()).Min();
            using (var cmd = new CommandBuffer { name = "CloudDetailCheck timing" })
            {
                for (int i = 0; i < reps; i++) record(cmd);
                var sw = System.Diagnostics.Stopwatch.StartNew();
                Graphics.ExecuteCommandBuffer(cmd); StormLabTestKit.Sync();
                return Math.Max(0, sw.Elapsed.TotalMilliseconds - idle) / reps;
            }
        }

        var energy = new Dictionary<string, float>(); var march = new Dictionary<string, double>();
        foreach (var v in views)
        {
            storm.stormMinutes = v.min; storm.StepTo(v.min, storm.Clock, true);
            foreach (var x in Wait(0.5f)) yield return x;
            var u = storm.UpdraftWorld(storm.StormTime);
            var k = storm.Lighting.keyDir;
            var toSun = new Vector3(k.x, 0f, k.y).normalized;
            var from = new Vector3(u.x, 0f, u.z) + Quaternion.Euler(0, v.sideDeg, 0) * toSun * v.km * 1000f;
            from.y = Physics.Raycast(from + Vector3.up * 3000f, Vector3.down, out var hit, 6000f) ? hit.point.y + 2f : 2f;
            var target = new Vector3(u.x, from.y + v.aimKm * 1000f, u.z);
            cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(target - from, Vector3.up));
            // a first render at a new spot streams in the map's trees and textures; draw one and throw it away
            // (and HDRP's motion blur smears them the first frames after a camera jump)
            StormLabTestKit.Render(cam, Path.Combine(ShotDir, "detail_warmup.png"), 1920, 1080, 12);
            var paths = new List<string>();
            foreach (var m in modes)
            {
                SetMode(m);
                storm.ResetHistory(cam);
                string path = Path.Combine(ShotDir, $"detail_{v.name}_{m}.png");
                StormLabTestKit.Render(cam, path, 1920, 1080, 8);
                paths.Add(path);
                double ms = Timed(20, c => storm.RecordMarch(c, cam, null, 1920, 1080, false, out _));
                float e = DetailEnergy(path);
                energy[v.name + m] = e; march[v.name + m] = ms;
                rep.AppendLine($"| {v.name} | {v.min:0.0} | {storm.Frame.stage} | {m} | {ms:0.00} ms | {e:0.000} |");
                yield return null;
            }
            Sheet(paths[0], paths[1], Path.Combine(ShotDir, $"detail_{v.name}_sheet.png"));
        }
        SetMode(modes[0]);
        rep.AppendLine();
        foreach (var v in views) rep.AppendLine($"- {v.name}: {v.what}; images differ by {ImageDiff(Path.Combine(ShotDir, $"detail_{v.name}_{modes[0]}.png"), Path.Combine(ShotDir, $"detail_{v.name}_{modes[1]}.png")) * 100:0.00} % (mean)");
        rep.AppendLine().AppendLine($"Sheets: `Screenshots/detail_<view>_sheet.png` ({modes[0]} left, {modes[1]} right; full frames above, 1:1 centre crops below).");
        if (field != null)
        {
            float worst = views.Max(v => (float)(march[v.name + "Enhanced"] - march[v.name + "Website"]));
            Check(views.All(v => energy[v.name + "Enhanced"] >= energy[v.name + "Website"] * 0.98f), "enhanced detail is at least as crisp in every view");
            Check(worst < 1.5f, $"the enhanced detail costs under 1.5 ms of march at 1080p in every view (worst {worst:+0.00;-0.00} ms)");
        }
    }

    /// <summary>Mean absolute Laplacian of luminance (0..255 scale) over the upper half of the frame, above the horizon in
    /// these views (the ground's texture and the map's trees would swamp it): how much fine detail the storm shows.</summary>
    static float DetailEnergy(string path)
    {
        var t = new Texture2D(2, 2); t.LoadImage(File.ReadAllBytes(path));
        var p = t.GetPixels32(); int w = t.width, h = t.height;
        float L(int i) => 0.2126f * p[i].r + 0.7152f * p[i].g + 0.0722f * p[i].b;
        double s = 0; long n = 0;
        for (int y = h / 2; y < h - 1; y++) for (int x = 1; x < w - 1; x++)
        {
            int i = y * w + x;
            s += Math.Abs(4f * L(i) - L(i - 1) - L(i + 1) - L(i - w) - L(i + w)); n++;
        }
        Object.DestroyImmediate(t);
        return (float)(s / n);
    }

    static float ImageDiff(string a, string b)
    {
        var ta = new Texture2D(2, 2); ta.LoadImage(File.ReadAllBytes(a));
        var tb = new Texture2D(2, 2); tb.LoadImage(File.ReadAllBytes(b));
        var pa = ta.GetPixels32(); var pb = tb.GetPixels32();
        double s = 0;
        for (int i = 0; i < pa.Length; i++) s += Math.Abs(pa[i].r - pb[i].r) + Math.Abs(pa[i].g - pb[i].g) + Math.Abs(pa[i].b - pb[i].b);
        Object.DestroyImmediate(ta); Object.DestroyImmediate(tb);
        return (float)(s / (pa.Length * 3.0 * 255.0));
    }

    /// <summary>1920 x 1080: the two frames at half size above, the centre 960 x 540 of each at 1:1 below.</summary>
    static void Sheet(string a, string b, string path)
    {
        var ta = new Texture2D(2, 2); ta.LoadImage(File.ReadAllBytes(a));
        var tb = new Texture2D(2, 2); tb.LoadImage(File.ReadAllBytes(b));
        int W = ta.width, H = ta.height;
        var o = new Texture2D(W, H, TextureFormat.RGB24, false);
        var px = new Color32[W * H];
        var pa = ta.GetPixels32(); var pb = tb.GetPixels32();
        int hw = W / 2, hh = H / 2;
        for (int y = 0; y < hh; y++) for (int x = 0; x < hw; x++)
        {
            // rows run bottom-up: the upper half holds the half-size frames, the lower half the crops
            px[(y + hh) * W + x] = pa[(2 * y) * W + 2 * x];
            px[(y + hh) * W + x + hw] = pb[(2 * y) * W + 2 * x];
            px[y * W + x] = pa[(y + hh / 2) * W + x + hw / 2];
            px[y * W + x + hw] = pb[(y + hh / 2) * W + x + hw / 2];
        }
        for (int y = 0; y < H; y++) { px[y * W + hw] = new Color32(255, 255, 255, 255); }
        o.SetPixels32(px); o.Apply();
        File.WriteAllBytes(path, o.EncodeToPNG());
        Object.DestroyImmediate(ta); Object.DestroyImmediate(tb); Object.DestroyImmediate(o);
    }
}
