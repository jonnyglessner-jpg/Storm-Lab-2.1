// Play-mode check of the storm and lighting panel's 24 hour clock: enters Play on the test map, holds the storm at its
// first mature cycle, and renders the chaser's view at dawn, morning, noon, afternoon, sunset, dusk, night under a full
// moon and night under a new moon, through the panel (sun, moon, HDRP sky, the storm's lighting and the exposure).
// Screenshots/day_*.png and a contact sheet day_sheet.jpg, validation/reports/StormDayCheck.md.
//   StormLab > Test Map > Day and Night Check
// Batch: -executeMethod StormDayCheck.RunFromCommandLine (never with -nographics)
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using StormLab;
using StormLab.Lightning;
using StormLab.TestMap;
using UnityEditor;
