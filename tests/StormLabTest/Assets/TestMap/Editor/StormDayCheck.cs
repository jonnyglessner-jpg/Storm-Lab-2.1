[InitializeOnLoad]
public static class StormDayCheck
{
    const string Key = "StormDayCheck.Active", BatchKey = "StormDayCheck.Batch", CodeKey = "StormDayCheck.Code";
    static string ShotDir => Path.Combine(StormLabTestKit.ProjectDir, "Screenshots");
    static string ReportPath => Path.Combine(StormLabTestKit.RepoRoot, "validation", "reports", "StormDayCheck.md");

    static StormDayCheck() { if (SessionState.GetBool(Key, false)) EditorApplication.playModeStateChanged += OnState; }

    [MenuItem("StormLab/Test Map/Day and Night Check")]
    public static void RunMenu() => Begin(false);
    public static void RunFromCommandLine() => Begin(true);

    static void Begin(bool batch)
    {
        EditorSceneManager.OpenScene(TestMapBuilder.ScenePath, OpenSceneMode.Single);
        SessionState.SetBool(Key, true); SessionState.SetBool(BatchKey, batch);
        EditorApplication.playModeStateChanged -= OnState;
        EditorApplication.playModeStateChanged += OnState;
        EditorApplication.EnterPlaymode();
    }

    static IEnumerator<object> routine; static readonly StringBuilder rep = new StringBuilder(); static bool ok; static int errors;
    static readonly List<string> errorLines = new List<string>();

    static void OnState(PlayModeStateChange s)
    {
        if (s == PlayModeStateChange.EnteredPlayMode)
        {
            rep.Clear(); ok = true; errors = 0; errorLines.Clear();
            Application.logMessageReceived += OnLog;
            routine = Run().GetEnumerator();
            EditorApplication.update += Tick;
        }
        else if (s == PlayModeStateChange.EnteredEditMode && SessionState.GetBool(Key, false))
        {
            SessionState.SetBool(Key, false);
            EditorApplication.playModeStateChanged -= OnState;
            if (SessionState.GetBool(BatchKey, false)) EditorApplication.Exit(SessionState.GetInt(CodeKey, 1));
        }
    }

    static void OnLog(string msg, string stack, LogType t)
    {
        if (t != LogType.Error && t != LogType.Exception && t != LogType.Assert) return;
        if (stack != null && stack.Contains("UnityEditor.Search")) return;   // Unity's search indexer, not StormLab's
        errors++; if (errorLines.Count < 10) errorLines.Add($"{t}: {msg.Split('\n')[0]}");
    }

    static void Tick()
    {
        if (!EditorApplication.isPlaying) return;
        bool more;
        try { more = routine.MoveNext(); }
        catch (Exception e) { Debug.LogException(e); ok = false; more = false; }
        if (more) return;
        EditorApplication.update -= Tick;
        Application.logMessageReceived -= OnLog;
        rep.AppendLine().AppendLine($"Errors logged: {errors}");
        foreach (var l in errorLines) rep.AppendLine($"- {l}");
        ok &= errors == 0;
        rep.Insert(0, $"# Day and night check: {(ok ? "PASS" : "FAIL")}\n\nGenerated by `StormDayCheck` on {DateTime.Now:yyyy-MM-dd HH:mm}, {SystemInfo.graphicsDeviceName}.\n\n");
        Directory.CreateDirectory(Path.GetDirectoryName(ReportPath));
        File.WriteAllText(ReportPath, rep.ToString());
        Debug.Log($"[StormDay] {(ok ? "PASS" : "FAIL")}; report {ReportPath}");
        SessionState.SetInt(CodeKey, ok ? 0 : 1);
        EditorApplication.ExitPlaymode();
    }

    static IEnumerable<object> Frames(int n) { for (int i = 0; i < n; i++) yield return null; }
    /// <summary>n player frames (in batch the editor's update ticks far more often than the player's frames)</summary>
    static IEnumerable<object> PlayerFrames(int n) { int f0 = Time.frameCount; while (Time.frameCount < f0 + n) yield return null; }

    static IEnumerable<object> Run()
    {
        foreach (var x in Frames(30)) yield return x;
        var world = Object.FindAnyObjectByType<TestMapWorld>();
        var panel = world ? world.GetComponent<TestMapStormPanel>() : null;
        var storm = world ? world.storm : null;
        var cam = Camera.main;
        if (!panel || !storm || !cam) { ok = false; rep.AppendLine($"FAIL: panel {panel}, storm {storm}, camera {cam}"); yield break; }
        var rig = cam.GetComponent<TestMapCamera>(); if (rig) rig.enabled = false;
        var sl = storm.GetComponent<StormLightning>(); if (sl && sl.Flashes) { sl.Flashes.enabled = false; sl.Bridge.enabled = false; }
        storm.playing = false;
        var P = storm.Plan;
        float t = P.cycles != null ? (float)P.cycles[0].times[3] : 50f;
        storm.StormTime = t;
        world.PlaceStorm();
        // the chaser, 9 km off the tornado (or the updraft), square to the storm's motion
        storm.StepTo(t, storm.Clock, true);
        var u = storm.UpdraftWorld(t);
        var target = storm.TornadoAmount > 0.15f ? storm.TornadoGroundWorld : new Vector3(u.x, 0, u.z);
        var mv = new Vector3((float)P.motion.x, 0, (float)P.motion.y).normalized;
        var from = target + Quaternion.Euler(0, 110, 0) * mv * 9000f;
        from.y = Physics.Raycast(from + Vector3.up * 3000f, Vector3.down, out var hit, 6000f) ? hit.point.y + 2f : 2f;
        cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(new Vector3(target.x, from.y + 1100f, target.z) - from, Vector3.up));
        rep.AppendLine($"Storm: {storm.preset} seed {storm.seed} at {t:0.0} min ({storm.Frame.stage}); camera 9 km off; day {panel.dayOfYear}, latitude {panel.latitude:0.00}; physical lighting, auto exposure.").AppendLine();
        // -slDayQuick: only the twilight sweep and the truck's lights
        if (System.Environment.GetCommandLineArgs().Contains("-slDayQuick"))
        {
            foreach (var x in Twilight(panel, storm, cam, t, from, target)) yield return x;
            foreach (var x in TruckLights(world, panel, storm, cam, t)) yield return x;
            yield break;
        }
        rep.AppendLine("| view | solar time | sun az / el | moon el, phase | key light | scene level | EV100 | mean brightness |").AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- |");
        var views = new (string name, float hour, float phase)[]
        {
            ("dawn", 5.4f, 0.5f), ("morning", 8f, 0.5f), ("noon", 12f, 0.5f), ("afternoon", 16f, 0.5f),
            ("sunset", 19.1f, 0.5f), ("dusk", 19.8f, 0.5f), ("night_fullmoon", 23f, 0.5f), ("night_newmoon", 23f, 0f),
        };
        var lum = new List<float>();
        foreach (var v in views)
        {
            panel.hour = v.hour; panel.moonPhase = v.phase; panel.clockRuns = false;
            panel.Apply();
            storm.StepTo(t, storm.Clock, true);
            storm.ResetHistory(cam);
            foreach (var x in Frames(3)) yield return x;
            string path = Path.Combine(ShotDir, $"day_{v.name}.png");
            StormLabTestKit.Render(cam, path, 1600, 900, 6);
            var tex = new Texture2D(2, 2); tex.LoadImage(File.ReadAllBytes(path));
            float mean = tex.GetPixels32().Average(c => (c.r + c.g + c.b) / 3f) / 255f; Object.DestroyImmediate(tex);
            lum.Add(mean);
            var L = storm.Lighting;
            rep.AppendLine($"| {v.name} | {Mathf.FloorToInt(v.hour):00}:{Mathf.FloorToInt(v.hour * 60 % 60):00} | {panel.SunAzEl.x:0} / {panel.SunAzEl.y:0.0} | {panel.MoonAzEl.y:0.0}, {v.phase:0.00} | {(L.keyIsMoon ? "moon" : "sun")} | {L.level:0.0E+0} | {panel.ExposureEV:0.0} | {mean * 100:0} % |");
        }
        rep.AppendLine();
        // sanity: a visible picture at every time, darker at night than by day, the new moon darker than the full
        // (a night is dark: from 2026-10-26 a moonlit night is shown at 1.2 % of day, so it only has to show something)
        bool visible = lum.Select((l, i) => i < 6 ? l > 0.02f && l < 0.95f : l > 0.005f).All(x => x);
        rep.AppendLine($"- {(visible ? "PASS" : "FAIL")}: every view shows something (mean brightness 2-95 % by day and dusk, over 0.5 % at night)");
        bool nightDarker = lum[6] < lum[2] && lum[7] <= lum[6] + 0.005f;
        rep.AppendLine($"- {(nightDarker ? "PASS" : "FAIL")}: night is darker than noon, and the new-moon night no brighter than the full-moon night");
        ok &= visible && nightDarker;
        // a contact sheet
        var sheet = new Texture2D(1600, 900 / 2 * 4 / 2 * 2, TextureFormat.RGB24, false);
        int cw = 800, ch = 450;
        sheet.Reinitialize(cw * 2, ch * 4);
        for (int i = 0; i < views.Length; i++)
        {
            var tex = new Texture2D(2, 2); tex.LoadImage(File.ReadAllBytes(Path.Combine(ShotDir, $"day_{views[i].name}.png")));
            var small = Scale(tex, cw, ch);
            int col = i % 2, row = 3 - i / 2;
            sheet.SetPixels(col * cw, row * ch, cw, ch, small);
            Object.DestroyImmediate(tex);
        }
        sheet.Apply();
        File.WriteAllBytes(Path.Combine(ShotDir, "day_sheet.jpg"), sheet.EncodeToJPG(88));
        Object.DestroyImmediate(sheet);
        rep.AppendLine().AppendLine("Images: `Screenshots/day_*.png`; contact sheet `Screenshots/day_sheet.jpg` (left to right, top to bottom: " + string.Join(", ", views.Select(v => v.name)) + ").");
        foreach (var x in Twilight(panel, storm, cam, t, from, target)) yield return x;

        // Night: what lights the storm. Both nights with the storm's town light off, then its night fill off too; the
        // storm (the frame's upper 55 %) and the ground (its lower 30 %) measured apart, mean brightness 0..100 %
        rep.AppendLine().AppendLine("## Night: what lights the storm").AppendLine();
        rep.AppendLine("| night | town light | night fill | storm (upper 55 %) | ground (lower 30 %) | EV100 |").AppendLine("| --- | --- | --- | --- | --- | --- |");
        float town0 = storm.lightPollution, fill0 = storm.nightFill;
        foreach (var (name, phase) in new[] { ("full moon", 0.5f), ("new moon", 0f) })
            foreach (var (town, fill) in new[] { (town0, fill0), (0f, fill0), (0f, 0f) })
            {
                storm.lightPollution = town; storm.nightFill = fill;
                panel.hour = 23f; panel.moonPhase = phase; panel.clockRuns = false; panel.Apply();
                storm.StepTo(t, storm.Clock, true); storm.ResetHistory(cam);
                foreach (var x in Frames(3)) yield return x;
                string path = Path.Combine(ShotDir, $"night_{(phase > 0 ? "full" : "new")}_t{town:0.00}_f{fill:0.00}.png");
                StormLabTestKit.Render(cam, path, 800, 450, 6);
                var tex = new Texture2D(2, 2); tex.LoadImage(File.ReadAllBytes(path));
                var px = tex.GetPixels32(); int w = tex.width, hh = tex.height;
                double up = 0, lo = 0; int nu = 0, nlo = 0;
                for (int y = 0; y < hh; y++) for (int x = 0; x < w; x++)
                {
                    var c = px[y * w + x]; float v = (c.r + c.g + c.b) / 765f;
                    if (y > hh * 0.45f) { up += v; nu++; } else if (y < hh * 0.3f) { lo += v; nlo++; }
                }
                Object.DestroyImmediate(tex);
                rep.AppendLine($"| {name} | {town:0.00} | {fill:0.00} | {up / nu * 100:0.0} % | {lo / nlo * 100:0.0} % | {panel.ExposureEV:0.0} |");
            }
        storm.lightPollution = town0; storm.nightFill = fill0;

        // The storm's shadow on the scene (StormSceneShadow): from 3 km up, 30 km off, looking across the storm and the
        // ground round it at noon and in the afternoon, with the shadow and without it
        rep.AppendLine().AppendLine("## The storm's shadow on the ground").AppendLine();
        var aerial = target + Quaternion.Euler(0, 200, 0) * mv * 30000f; aerial.y = 3000f;
        cam.transform.SetPositionAndRotation(aerial, Quaternion.LookRotation(new Vector3(target.x, 0f, target.z) - aerial, Vector3.up));
        foreach (var (name, hour) in new[] { ("noon", 12f), ("afternoon", 16f) })
            foreach (bool shadow in new[] { true, false })
            {
                storm.castSceneShadow = shadow;
                var ssh = storm.sun ? storm.sun.GetComponent<StormSceneShadow>() : null;
                if (ssh) ssh.enabled = shadow;
                panel.hour = hour; panel.moonPhase = 0.5f; panel.clockRuns = false; panel.Apply();
                storm.StepTo(t, storm.Clock, true); storm.ResetHistory(cam);
                foreach (var x in Frames(12)) yield return x;
                string path = Path.Combine(ShotDir, $"shadow_{name}_{(shadow ? "on" : "off")}.png");
                StormLabTestKit.Render(cam, path, 1600, 900, 6);
                rep.AppendLine($"- `Screenshots/shadow_{name}_{(shadow ? "on" : "off")}.png`: {name}, shadow {(shadow ? "on" : "off")}");
            }
        storm.castSceneShadow = true;
        { var ssh = storm.sun ? storm.sun.GetComponent<StormSceneShadow>() : null; if (ssh) ssh.enabled = true; }
        // straight down from 40 km over the storm, north up, at 17:30 (sun in the west, about 20 degrees up): the
        // shadows must lie to the east of the clouds that cast them
        cam.transform.SetPositionAndRotation(new Vector3(target.x, 40000f, target.z), Quaternion.LookRotation(Vector3.down, Vector3.forward));
        float fov0 = cam.fieldOfView; cam.fieldOfView = 90f;
        panel.hour = 17.5f; panel.Apply();
        storm.StepTo(t, storm.Clock, true); storm.ResetHistory(cam);
        foreach (var x in Frames(12)) yield return x;
        StormLabTestKit.Render(cam, Path.Combine(ShotDir, "shadow_above.png"), 1200, 1200, 6);
        rep.AppendLine($"- `Screenshots/shadow_above.png`: straight down from 40 km, north up, east right, 17:30 (sun az {panel.SunAzEl.x:0}, el {panel.SunAzEl.y:0})");
        cam.fieldOfView = fov0;

        // The night lights (TestMapNightLights): the barn nearest the truck from 30 m in front of its door, at night and
        // by day, and the truck from behind with its headlights on, at night
        rep.AppendLine().AppendLine("## Night lights").AppendLine();
        var nlights = Object.FindAnyObjectByType<TestMapNightLights>();
        var yard = nlights && nlights.yardLights ? nlights.yardLights.GetComponentsInChildren<Light>(true) : new Light[0];   // (inactive ones too)
        var carT = world.car ? world.car.transform : null;
        if (!nlights || yard.Length == 0 || !carT) { ok = false; rep.AppendLine($"- FAIL: night lights {nlights}, yard lights {yard.Length}, truck {carT}"); yield break; }
        var barn = yard.OrderBy(l => (l.transform.position - carT.position).sqrMagnitude).First();
        var outward = Vector3.ProjectOnPlane(barn.transform.forward, Vector3.up).normalized;
        var eye = barn.transform.position + outward * 30f; eye.y = barn.transform.position.y - 3f;
        cam.transform.SetPositionAndRotation(eye, Quaternion.LookRotation(barn.transform.position - Vector3.up * 2.5f - eye, Vector3.up));
        foreach (var (name, hour) in new[] { ("night", 23f), ("day", 16f) })
        {
            panel.hour = hour; panel.moonPhase = 0.5f; panel.Apply();
            storm.StepTo(t, storm.Clock, true); storm.ResetHistory(cam);
            foreach (var x in Frames(6)) yield return x;
            string path = Path.Combine(ShotDir, $"lights_barn_{name}.png");
            StormLabTestKit.Render(cam, path, 1200, 675, 6);
            rep.AppendLine($"- `Screenshots/lights_barn_{name}.png`: the barn nearest the truck, 30 m off its door, {name}; its yard light {(barn.isActiveAndEnabled ? "on" : "off")}");
        }
        bool barnOk = !barn.isActiveAndEnabled;   // off by day (the last view)
        panel.hour = 23f; panel.Apply();
        foreach (var x in Frames(40)) yield return x;   // (the near lights are switched twice a second)
        barnOk &= barn.isActiveAndEnabled;
        rep.AppendLine($"- {(barnOk ? "PASS" : "FAIL")}: yard lights off by day, on at night ({yard.Length} yard lights)");
        ok &= barnOk;
        foreach (var x in TruckLights(world, panel, storm, cam, t)) yield return x;

        // Lightning at night (user, 2026-10-26: blinding, now and then glitching): flashes at real time under a full moon
        // for 25 s from the chaser's spot, with the night scaling (StormRenderer.LightningScale) and without it. Frames
        // read back in half float, so a value that overflowed (infinite or not a number) is counted, not hidden by the
        // 8-bit picture; the brightest frame of each run saved.
        rep.AppendLine().AppendLine("## Lightning at night").AppendLine();
        rep.AppendLine("| night scaling (lightningAtNight) | lightning scale | frames | brightest frame (mean) | broken pixels (inf / NaN) |").AppendLine("| --- | --- | --- | --- | --- |");
        // -slFlashAtNight a,b,c: also try these lightningAtNight values (the game's default first)
        var argv = System.Environment.GetCommandLineArgs(); int fi = Array.IndexOf(argv, "-slFlashAtNight");
        var tries = new List<float> { storm.lightningAtNight };
        if (fi >= 0 && fi + 1 < argv.Length) tries.AddRange(argv[fi + 1].Split(',').Select(x => float.Parse(x, System.Globalization.CultureInfo.InvariantCulture)));
        float atNight0 = storm.lightningAtNight;
        var sl2 = storm.GetComponent<StormLightning>();
        if (sl2 && sl2.Flashes) { sl2.Flashes.enabled = true; if (sl2.Bridge) sl2.Bridge.enabled = true; }
        panel.hour = 23f; panel.moonPhase = 0.5f; panel.Apply();
        cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(new Vector3(target.x, from.y + 1100f, target.z) - from, Vector3.up));
        storm.minutesPerSecond = 1f / 60f; storm.playing = true;
        bool flashOk = true;
        var runs = tries.Select(v => (scaled: true, v)).Append((scaled: false, v: atNight0)).ToList();
        foreach (var (scaled, v) in runs)
        {
            storm.exposureAdaptsAtNight = scaled; storm.lightningAtNight = v;
            bool first = scaled && v == atNight0;
            float bestMean = -1f; Color[] best = null; int frames = 0, broken = 0;
            float t0 = Time.realtimeSinceStartup;
            int frame = 0;
            while (Time.realtimeSinceStartup - t0 < (runs.Count > 2 ? 15f : 25f))
            {
                yield return null;
                if (++frame % 3 != 0) continue;
                var px = CaptureHdr(cam, 480, 270);
                frames++;
                double sum = 0;
                foreach (var c in px)
                {
                    if (float.IsNaN(c.r + c.g + c.b) || float.IsInfinity(c.r + c.g + c.b)) { broken++; continue; }
                    sum += (c.r + c.g + c.b) / 3f;
                }
                float mean = (float)(sum / px.Length);
                if (mean > bestMean) { bestMean = mean; best = px; }
            }
            if (best != null)
            {
                var tex = new Texture2D(480, 270, TextureFormat.RGB24, false);
                for (int i = 0; i < best.Length; i++) { var c = best[i]; best[i] = new Color(Mathf.Clamp01(c.r), Mathf.Clamp01(c.g), Mathf.Clamp01(c.b)); }
                tex.SetPixels(best); tex.Apply();
                File.WriteAllBytes(Path.Combine(ShotDir, $"lightning_night_{(scaled ? "scaled" + v.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture) : "unscaled")}.png"), tex.EncodeToPNG());
                Object.DestroyImmediate(tex);
            }
            rep.AppendLine($"| {(scaled ? $"on ({v:0.###})" : "off (as before)")} | {storm.LightningScale:0.00000} | {frames} | {bestMean * 100:0.0} % | {broken} |");
            if (first) flashOk &= broken == 0 && bestMean < 0.9f;
        }
        storm.exposureAdaptsAtNight = true; storm.lightningAtNight = atNight0; storm.playing = false;
        rep.AppendLine().AppendLine($"- {(flashOk ? "PASS" : "FAIL")}: with the night scaling no broken pixels and no frame washed out (brightest frame's mean under 90 %); images `Screenshots/lightning_night_*.png`");
        ok &= flashOk;
    }

    /// <summary>Mean brightness 0..1 of a picture's upper 55 % (the storm, in the chaser's view) and lower 30 % (the ground).</summary>
    static (float up, float low) UpLow(string path)
    {
        var tex = new Texture2D(2, 2); tex.LoadImage(File.ReadAllBytes(path));
        var px = tex.GetPixels32(); int w = tex.width, hh = tex.height;
        double up = 0, lo = 0; int nu = 0, nlo = 0;
        for (int y = 0; y < hh; y++) for (int x = 0; x < w; x++)
        {
            var c = px[y * w + x]; float v = (c.r + c.g + c.b) / 765f;
            if (y > hh * 0.45f) { up += v; nu++; } else if (y < hh * 0.3f) { lo += v; nlo++; }
        }
        Object.DestroyImmediate(tex);
        return ((float)(up / nu), (float)(lo / nlo));
    }

    /// <summary>
    /// Twilight (user, 2026-10-30: the ground black as at midnight while the clouds still had sunlight): the chaser's view
    /// from sunset into night, with the panel's sky fill and without it; the storm and the ground measured apart. With it,
    /// the ground must fade steadily (no step where HDRP's sun Light goes out) and keep about the share of the storm's
    /// brightness it has at sunset until the twilight sky is gone.
    /// </summary>
    static IEnumerable<object> Twilight(TestMapStormPanel panel, StormRenderer storm, Camera cam, float t, Vector3 from, Vector3 target)
    {
        rep.AppendLine().AppendLine("## Twilight: the ground and the storm").AppendLine();
        rep.AppendLine("Chaser's view, full moon; mean brightness of the storm (upper 55 %) and the ground (lower 30 %), with the panel's sky fill and without it.").AppendLine();
        rep.AppendLine("| solar time | sun el | EV100 | sky fill, lux | storm | ground | ground / storm | ground, no fill |").AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- |");
        cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(new Vector3(target.x, from.y + 1100f, target.z) - from, Vector3.up));
        float[] hours = { 18.6f, 18.9f, 19.1f, 19.25f, 19.4f, 19.55f, 19.7f, 19.85f, 20.0f, 20.2f, 20.5f, 21f };
        var ground = new List<float>(); var stormB = new List<float>(); var ratio = new List<float>(); var grounds0 = new List<float>(); var els = new List<float>();
        bool fill0 = panel.skyFill;
        foreach (var h in hours)
        {
            var row = new float[2, 2]; float lux = 0f, ev = 0f;
            foreach (bool f in new[] { true, false })
            {
                panel.skyFill = f; panel.hour = h; panel.moonPhase = 0.5f; panel.clockRuns = false; panel.Apply();
                storm.StepTo(t, storm.Clock, true); storm.ResetHistory(cam);
                // (the storms' hiding of the sky, StormSceneAmbient, settles over about 1.5 s)
                float w0 = Time.realtimeSinceStartup;
                while (Time.realtimeSinceStartup - w0 < 3f) yield return null;
                panel.Apply();
                if (f) { lux = panel.SkyFillLux; ev = panel.ExposureEV; }
                string path = Path.Combine(ShotDir, $"twilight_{h:00.00}_{(f ? "fill" : "nofill")}.png");
                StormLabTestKit.Render(cam, path, 800, 450, 6);
                var (u, l) = UpLow(path);
                row[f ? 0 : 1, 0] = u; row[f ? 0 : 1, 1] = l;
            }
            ground.Add(row[0, 1]); stormB.Add(row[0, 0]); ratio.Add(row[0, 1] / Mathf.Max(row[0, 0], 1e-4f)); grounds0.Add(row[1, 1]); els.Add(panel.SunAzEl.y);
            rep.AppendLine($"| {Mathf.FloorToInt(h):00}:{Mathf.FloorToInt(h * 60 % 60):00} | {panel.SunAzEl.y:0.0} | {ev:0.0} | {lux:0.###} | {row[0, 0] * 100:0.0} % | {row[0, 1] * 100:0.0} % | {ratio[ratio.Count - 1]:0.00} | {row[1, 1] * 100:0.0} % |");
        }
        panel.skyFill = fill0;
        // no step up: the ground at each later time no brighter than the one before, beyond the storm's own change (the
        // exposure opens through twilight) and half a percent of the frame
        bool steady = true;
        for (int i = 1; i < ground.Count; i++) steady &= ground[i] <= ground[i - 1] * Mathf.Max(1f, stormB[i] / Mathf.Max(stormB[i - 1], 1e-4f)) + 0.005f;
        // the ground keeps a fair share of its sunset look while the sun is 0-6 degrees down
        float r0 = ratio[0];
        bool kept = true;
        for (int i = 0; i < ground.Count; i++) if (els[i] < 0f && els[i] > -6f) kept &= ratio[i] > 0.3f * r0;
        rep.AppendLine().AppendLine($"- {(steady ? "PASS" : "FAIL")}: the ground darkens steadily from sunset into night (no step brighter than the storm's)");
        rep.AppendLine($"- {(kept ? "PASS" : "FAIL")}: with the sun 0-6 degrees down the ground keeps over 30 % of its share of the storm's brightness at {hours[0]:0.0} h");
        rep.AppendLine("- Images: `Screenshots/twilight_<hour>_fill.png` and `_nofill.png`");
        ok &= steady && kept;
    }

    /// <summary>
    /// The truck's lights (user, 2026-10-30: on at any time, covering more ground; L cycles off, low, high with the light
    /// bar): from behind the truck and from 120 m above the road ahead, each mode at night under a full moon and at dusk;
    /// the ground ahead measured in the view from above, near (10-30 m ahead) and far (60-150 m).
    /// </summary>
    static IEnumerable<object> TruckLights(TestMapWorld world, TestMapStormPanel panel, StormRenderer storm, Camera cam, float t)
    {
        rep.AppendLine().AppendLine("## The truck's lights").AppendLine();
        var nl = Object.FindAnyObjectByType<TestMapNightLights>();
        var carT = world.car ? world.car.transform : null;
        if (!nl || !carT) { ok = false; rep.AppendLine($"- FAIL: night lights {nl}, truck {carT}"); yield break; }
        rep.AppendLine("| time | mode | near road (10-30 m) | far road (60-150 m) | lights on | EV100 | boost | low beam, cd | high beam, cd |").AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
        var fwd = Vector3.ProjectOnPlane(carT.forward, Vector3.up).normalized;
        var mode0 = nl.headlightMode;
        var means = new Dictionary<(string, TestMapNightLights.Headlights), (float near, float far)>();
        bool lightsOk = true;
        foreach (var (name, hour) in new[] { ("night", 23f), ("dusk", 19.8f) })
            foreach (var mode in new[] { TestMapNightLights.Headlights.Off, TestMapNightLights.Headlights.Low, TestMapNightLights.Headlights.High })
            {
                panel.hour = hour; panel.moonPhase = 0.5f; panel.clockRuns = false; panel.Apply();
                nl.headlightMode = mode;
                storm.StepTo(t, storm.Clock, true);
                foreach (var x in PlayerFrames(3)) yield return x;
                var lights = carT.GetComponentsInChildren<Light>().Where(l => l.isActiveAndEnabled).ToArray();
                bool want = mode == TestMapNightLights.Headlights.Off ? lights.Length == 0 : mode == TestMapNightLights.Headlights.Low ? lights.Length == 2 : lights.Length == 5;
                lightsOk &= want;
                // from behind
                var behind = carT.position - fwd * 12f + Vector3.up * 6f;
                cam.transform.SetPositionAndRotation(behind, Quaternion.LookRotation(carT.position + fwd * 40f - behind, Vector3.up));
                storm.ResetHistory(cam);
                foreach (var x in PlayerFrames(3)) yield return x;
                StormLabTestKit.Render(cam, Path.Combine(ShotDir, $"lights_truck_{name}_{mode.ToString().ToLowerInvariant()}.png"), 1200, 675, 6);
                // from above: the road ahead, the truck at the bottom edge, ahead up the picture
                var mid = carT.position + fwd * 75f;
                cam.transform.SetPositionAndRotation(mid + Vector3.up * 130f, Quaternion.LookRotation(Vector3.down, fwd));
                storm.ResetHistory(cam);
                foreach (var x in PlayerFrames(3)) yield return x;
                string above = Path.Combine(ShotDir, $"lights_above_{name}_{mode.ToString().ToLowerInvariant()}.png");
                StormLabTestKit.Render(cam, above, 900, 900, 6);
                var (near, far) = Strip(above, cam, carT.position, fwd);
                means[(name, mode)] = (near, far);
                rep.AppendLine($"| {name} | {mode} | {near * 100:0.0} % | {far * 100:0.0} % | {lights.Length} | {panel.ExposureEV:0.0} | {nl.Boost:0.##} | {(nl.headlights.Length > 0 && nl.headlights[0] ? nl.headlights[0].intensity : 0f):0.###E+0} | {carT.GetComponentsInChildren<Light>(true).Where(l => l.name.StartsWith("High")).Select(l => l.intensity).DefaultIfEmpty(0f).First():0.###E+0} |");
            }
        nl.headlightMode = mode0;
        // each step lights more of the road, at dusk as at night
        bool more = true;
        foreach (var name in new[] { "night", "dusk" })
        {
            var o = means[(name, TestMapNightLights.Headlights.Off)]; var lo = means[(name, TestMapNightLights.Headlights.Low)]; var hi = means[(name, TestMapNightLights.Headlights.High)];
