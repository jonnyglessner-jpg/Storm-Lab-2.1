// Headless checks of a test map. Drives the truck with an autopilot down every state route, the paved county roads
// and the three longest gravel roads (scripted physics, 150 s each; on the real-data maps the ten longest highways and
// the three longest paved and gravel roads), slowing for curves, and checks it stays on the road, upright and on its
// wheels; then renders views of the map and of a storm to Screenshots/<map>_*.png and writes
// validation/reports/<Map>Report.md (TestMapReport.md for the plains map).
//   StormLab > Test Map > Run Drive Test + Screenshots   (and the same under Dixie Map and Midwest Map)
// Batch (never with -nographics): -executeMethod TestMapTests.RunFromCommandLine [-testmapShotsOnly] [-testmapMap dixie|midwest]
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using StormLab;
using StormLab.TestMap;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;
using Object = UnityEngine.Object;

public static class TestMapTests
{
    static string ProjectDir => Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
    static string ShotDir => Path.Combine(ProjectDir, "Screenshots");
    static bool Real => TestMapBuilder.Map.real;
    static bool Plains => TestMapBuilder.Map == TestMapBuilder.MapSpec.Plains;
    static string Prefix => Plains ? "testmap" : TestMapBuilder.Map.data.Replace("MapData", "").ToLowerInvariant();
    static string ReportPath => Path.GetFullPath(Path.Combine(ProjectDir, "..", "..", "validation", "reports",
        Plains ? "TestMapReport.md" : TestMapBuilder.Map.data.Replace("Data", "") + "Report.md"));

    [MenuItem("StormLab/Test Map/Run Drive Test + Screenshots")]
    public static void RunMenu() { TestMapBuilder.Map = TestMapBuilder.MapSpec.Plains; Run(false); }

    [MenuItem("StormLab/Dixie Map/Run Drive Test + Screenshots")]
    public static void RunDixieMenu() { TestMapBuilder.Map = TestMapBuilder.MapSpec.Dixie; try { Run(false); } finally { TestMapBuilder.Map = TestMapBuilder.MapSpec.Plains; } }

    [MenuItem("StormLab/Midwest Map/Run Drive Test + Screenshots")]
    public static void RunMidwestMenu() { TestMapBuilder.Map = TestMapBuilder.MapSpec.Midwest; try { Run(false); } finally { TestMapBuilder.Map = TestMapBuilder.MapSpec.Plains; } }

    public static void RunFromCommandLine()
    {
        bool ok;
        var args = System.Environment.GetCommandLineArgs();
        int k = Array.IndexOf(args, "-testmapMap");
        string map = k >= 0 && k + 1 < args.Length ? args[k + 1] : "plains";
        TestMapBuilder.Map = map == "dixie" ? TestMapBuilder.MapSpec.Dixie : map == "midwest" ? TestMapBuilder.MapSpec.Midwest : TestMapBuilder.MapSpec.Plains;
        try { ok = Run(args.Contains("-testmapShotsOnly")); }
        catch (Exception e) { Debug.LogException(e); ok = false; }
        EditorApplication.Exit(ok ? 0 : 1);
    }

    public static bool Run(bool shotsOnly)
    {
        EditorSceneManager.OpenScene(TestMapBuilder.ScenePath, OpenSceneMode.Single);
        ShaderUtil.allowAsyncCompilation = false;
        Directory.CreateDirectory(ShotDir);
        var world = Object.FindAnyObjectByType<TestMapWorld>();
        var car = world.car;
        var cam = Camera.main;
        var rep = new StringBuilder($"# {(Plains ? "Plains test map" : TestMapBuilder.Map.world)}\n\n");
        rep.AppendLine($"Generated by `TestMapTests` on {DateTime.Now:yyyy-MM-dd HH:mm}. Map: {world.sizeM / 1609.344f:0} x {world.sizeM / 1609.344f:0} miles.").AppendLine();
        bool ok = true;
        if (!shotsOnly) ok &= DriveTests(world, car, rep);
        ok &= Screenshots(world, car, cam, rep);
        Directory.CreateDirectory(Path.GetDirectoryName(ReportPath));
        File.WriteAllText(ReportPath, rep.ToString());
        Debug.Log($"[TestMap] overall {(ok ? "PASS" : "FAIL")}; report {ReportPath}");
        return ok;
    }

    // ------------------------------------------------------------------------------------------------- driving

    static bool DriveTests(TestMapWorld world, TestMapCar car, StringBuilder rep)
    {
        var prevMode = Physics.simulationMode;
        Physics.simulationMode = SimulationMode.Script;
        car.acceptInput = false;
        bool all = true;
        rep.AppendLine("## Drive test").AppendLine();
        rep.AppendLine("Autopilot at a road's design speed for 150 s (or to the road's end) from 2 km in from the map edge, slowing for curves ahead to keep under 3.5 m/s2 sideways. Pass: upright, at least 60 % of the distance the curves allow, never more than 3 m off the centre line, no wheel off the ground for more than 0.3 s, nothing fell through.").AppendLine();
        rep.AppendLine("| Road | Class | Target | Distance | Top speed | Max off centre | Longest airborne | Car root vs road surface | Result |").AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
        try
        {
            var picks = Real
                // real roads come in many pieces: the longest piece of each of the ten longest highways, then the longest paved and gravel
                ? world.routes.Where(r => r.cls == "state").GroupBy(r => r.name).Select(g => g.OrderByDescending(Length).First())
                    .OrderByDescending(Length).Take(10)
                    .Concat(world.routes.Where(r => r.cls == "paved").OrderByDescending(Length).Take(3))
                    .Concat(world.routes.Where(r => r.cls == "gravel").OrderByDescending(Length).Take(3)).ToList()
                : world.routes.Where(r => r.cls != "gravel").Concat(world.routes.Where(r => r.cls == "gravel").Take(3)).ToList();
            foreach (var route in picks)
            {
                var P = route.points;
                int i0 = Array.FindIndex(P, p => Mathf.Abs(p.x) < world.sizeM / 2 - 2000 && Mathf.Abs(p.z) < world.sizeM / 2 - 2000);
                if (i0 < 0 || i0 + 10 >= P.Length) continue;
                float vt = route.cls == "state" ? 105f : route.cls == "paved" ? 90f : 70f;
                var fwd = P[i0 + 1] - P[i0]; fwd.y = 0;
                car.Teleport(P[i0], Quaternion.LookRotation(fwd.normalized, Vector3.up));
                Physics.SyncTransforms();
                var start = car.transform.position;
                int near = i0;
                float maxDev = 0, maxKph = 0, air = 0, maxAir = 0, minClear = float.MaxValue, allowed = 0;
                var worstAt = start;
                bool fell = false;
                const float dt = 0.01f;
                for (int step = 0; step < 15000; step++)
                {
                    var pos = car.transform.position;
                    // nearest route point, searching forward only
                    while (near + 1 < P.Length && Flat(P[near + 1] - pos).sqrMagnitude < Flat(P[near] - pos).sqrMagnitude) near++;
                    // (the real-data maps' tight curves: a short look-ahead, or the car cuts across them)
                    float look = Real ? Mathf.Max(6f, car.SpeedKph / 3.6f * 0.6f) : 18f + car.SpeedKph / 3.6f * 0.9f;
                    int ti = near;
                    while (ti + 1 < P.Length && Flat(P[ti] - pos).magnitude < look) ti++;
                    var to = Flat(P[ti] - pos);
                    float ang = Vector3.SignedAngle(Flat(car.transform.forward), to, Vector3.up);
                    float steer = Mathf.Clamp(ang / 20f, -1f, 1f);
                    float v = car.SpeedKph;
                    // a driver's speed for the tightest curve within braking distance (3.5 m/s2 sideways)
                    float vc = vt;
                    for (int c = near + 1; c + 1 < P.Length && Flat(P[c] - P[near]).magnitude < 40f + v * v / 60f; c++)
                        vc = Mathf.Min(vc, Mathf.Max(25f, Mathf.Sqrt(3.5f * Radius(P[c - 1], P[c], P[c + 1])) * 3.6f));
                    float throttle = step < 50 ? 0 : Mathf.Clamp01((vc - v) / 12f);
                    float brake = v > vc + 8f ? Mathf.Max(0.4f, Mathf.Clamp01((v - vc) / 20f)) : 0f;
                    car.Step(throttle, steer, brake, false, dt);
                    Physics.Simulate(dt);
                    if (step < 100) continue;
                    allowed += vc / 3.6f * dt;        // how far the curves let it go
                    maxKph = Mathf.Max(maxKph, v);
                    float dev = DistToPolyline(P, near, pos);
                    if (dev > maxDev) { maxDev = dev; worstAt = pos; }
                    bool grounded = car.wheels.Any(w => w.collider.isGrounded);
                    air = grounded ? 0 : air + dt;
                    maxAir = Mathf.Max(maxAir, air);
                    if (step % 20 == 0)
                    {
                        if (Physics.Raycast(pos + Vector3.up * 0.3f, Vector3.down, out var hit, 60f, ~0, QueryTriggerInteraction.Ignore))
                            minClear = Mathf.Min(minClear, pos.y - hit.point.y);
                        else fell = true;
                    }
                    if (near >= P.Length - 3) break;
                }
                // driven along the road (a straight line from the start undercounts a winding road)
                float dist = 0; for (int k = i0; k < near; k++) dist += Flat(P[k + 1] - P[k]).magnitude;
                bool upright = Vector3.Dot(car.transform.up, Vector3.up) > 0.8f;
                bool pass = upright && !fell && maxDev < 3f && maxAir < 0.3f && (dist > 0.6f * allowed || near >= P.Length - 3);
                all &= pass;
                rep.AppendLine($"| {route.name} | {route.cls} | {vt * 0.621f:0} mph | {dist / 1609.344f:0.00} mi | {maxKph * 0.621f:0} mph | {maxDev:0.0} m | {maxAir:0.00} s | {(fell ? "fell" : $"{minClear:0.00} m")} | {(pass ? "PASS" : "FAIL")} |");
                Debug.Log($"[TestMap] drive {route.name} ({route.cls}): {(pass ? "PASS" : "FAIL")} {dist:0} m, top {maxKph:0} km/h, off centre {maxDev:0.0} m (at {worstAt.x:0}, {worstAt.z:0}), airborne {maxAir:0.00} s, upright {upright}");
            }
        }
        finally
        {
            Physics.simulationMode = prevMode;
            car.acceptInput = true;
        }
        rep.AppendLine();
        return all;
    }

    static Vector3 Flat(Vector3 v) { v.y = 0; return v; }

    static float Length(TestMapWorld.Route r) { float s = 0; for (int i = 1; i < r.points.Length; i++) s += Flat(r.points[i] - r.points[i - 1]).magnitude; return s; }

    /// <summary>Radius of the circle through three points (plan view); large on a straight.</summary>
    static float Radius(Vector3 a, Vector3 b, Vector3 c)
    {
        var ab = Flat(b - a); var bc = Flat(c - b); var ca = Flat(a - c);
        float cross = Mathf.Abs(ab.x * bc.z - ab.z * bc.x);
        return cross < 1e-4f ? 1e5f : ab.magnitude * bc.magnitude * ca.magnitude / (2f * cross);
    }

    static float DistToPolyline(Vector3[] P, int near, Vector3 p)
    {
        float best = float.MaxValue;
        for (int k = Mathf.Max(0, near - 2); k < Mathf.Min(P.Length - 1, near + 2); k++)
        {
            var a = Flat(P[k]); var b = Flat(P[k + 1]); var q = Flat(p);
            var ab = b - a; float t = Mathf.Clamp01(Vector3.Dot(q - a, ab) / Mathf.Max(ab.sqrMagnitude, 1e-6f));
            best = Mathf.Min(best, (a + ab * t - q).magnitude);
        }
        return best;
    }

    // --------------------------------------------------------------------------------------------- screenshots

    static void Sync() { var b = new ComputeBuffer(1, 4); var a = new int[1]; b.GetData(a); b.Release(); }

    static void Shot(Camera cam, Vector3 from, Vector3 lookAt, string name, float fov = 60f, int frames = 10)
    {
        cam.transform.SetPositionAndRotation(from, Quaternion.LookRotation(lookAt - from, Vector3.up));
        cam.fieldOfView = fov;
        var rt = new RenderTexture(1920, 1080, 24, RenderTextureFormat.ARGB32, RenderTextureReadWrite.sRGB) { antiAliasing = 1 };
        rt.Create();
        for (int f = 0; f < frames; f++)
        {
            var req = new RenderPipeline.StandardRequest { destination = rt };
            if (RenderPipeline.SupportsRenderRequest(cam, req)) RenderPipeline.SubmitRenderRequest(cam, req);
            else { cam.targetTexture = rt; cam.Render(); cam.targetTexture = null; }
        }
        var prev = RenderTexture.active; RenderTexture.active = rt;
        var tex = new Texture2D(rt.width, rt.height, TextureFormat.RGB24, false);
        tex.ReadPixels(new Rect(0, 0, rt.width, rt.height), 0, 0); tex.Apply();
        RenderTexture.active = prev;
        File.WriteAllBytes(Path.Combine(ShotDir, $"{Prefix}_{name}.png"), tex.EncodeToPNG());
        Object.DestroyImmediate(tex); rt.Release(); Object.DestroyImmediate(rt);
        Debug.Log($"[TestMap] shot {name}");
    }

    static float Ground(Vector3 p)
    {
        return Physics.Raycast(new Vector3(p.x, 3000f, p.z), Vector3.down, out var hit, 6000f, ~0, QueryTriggerInteraction.Ignore) ? hit.point.y : 0f;
    }

    static Vector3 OnGround(Vector3 p, float up) { p.y = Ground(p) + up; return p; }

    static bool Screenshots(TestMapWorld world, TestMapCar car, Camera cam, StringBuilder rep)
    {
        rep.AppendLine("## Views").AppendLine();
        var storm = world.storm;
        Physics.SyncTransforms();
        float S = world.sizeM / 2;
        var mid = OnGround(Vector3.zero, 0);
        Shot(cam, mid + new Vector3(0, 5, 0), mid + new Vector3(0, 0, 10), "_warmup", 60, 4);

        // the whole map, from high over its south-west corner
        Shot(cam, new Vector3(-S - 8000f, 9000f, -S - 8000f), new Vector3(0, 0, 0), "01_overview", 55);
        // a state route crossing (pad) and a state route past a county road (mouths)
        var (ja, jb) = Real ? StateCrossing(world) : ("K-19", "K-283");
        var k19 = world.routes.Where(r => r.name == ja).OrderByDescending(Length).First();
        var junction = Junction(world, ja, jb);
        Shot(cam, junction + new Vector3(-55, 45, -70), junction, "02_state_junction");
        // gravel section roads from a farm truck's height: the grid running off over the rise
        var gravel = Real ? world.routes.Where(r => r.cls == "gravel").OrderByDescending(Length).First() : world.routes.First(r => r.cls == "gravel");
        var gp = gravel.points[gravel.points.Length / 2];
        var gd = Flat(gravel.points[gravel.points.Length / 2 + 4] - gp).normalized;
        Shot(cam, OnGround(gp - gd * 6f + Vector3.Cross(Vector3.up, gd) * 1.2f, 1.7f), OnGround(gp + gd * 400f, 2f), "03_gravel_eye");
        // the truck on a state route, chase view
        int i = k19.points.Length / 3;
        var kd = Flat(k19.points[i + 1] - k19.points[i]).normalized;
        car.Teleport(k19.points[i] + Vector3.Cross(Vector3.up, kd) * 1.8f, Quaternion.LookRotation(kd));
        Physics.SyncTransforms();
        Shot(cam, OnGround(car.transform.position - kd * 9f, 3.2f), car.transform.position + Vector3.up * 1.2f + kd * 6f, "04_truck_state_route");
        // a river bridge from the bank
        var spot = world.spots.FirstOrDefault(s => s.name.Contains("river bridge"));
        if (!string.IsNullOrEmpty(spot.name))
        {
            var dir = Quaternion.Euler(0, spot.heading, 0) * Vector3.forward;
            var deck = spot.position + dir * 140f;
            var side = Vector3.Cross(Vector3.up, dir);
            // from the bank beside the approach, above the water
            var from = OnGround(spot.position + side * 60f + dir * 20f, 4f);
            Shot(cam, from, deck, "05_river_bridge");
        }
        // a farmstead, oblique
        var farm = TestMapBuilder.Farmsteads().OrderBy(f => (f - Vector3.zero).sqrMagnitude).FirstOrDefault();
        if (farm != Vector3.zero) Shot(cam, farm + new Vector3(-150, 70, -150), farm, "06_farmstead");
        // the horizon at eye level: fields, tree lines, poles
        Shot(cam, OnGround(new Vector3(gp.x, 0, gp.z) + Vector3.Cross(Vector3.up, gd) * 25f, 1.7f),
             OnGround(new Vector3(gp.x, 0, gp.z) + Vector3.Cross(Vector3.up, gd) * 3000f, 30f), "07_horizon", 70);
        // irrigated circles from a light plane (the real-data maps: the town)
        if (Real) Shot(cam, new Vector3(-1200f, 900f, -1600f), OnGround(Vector3.zero, 0), "08_town", 60);
        else Shot(cam, new Vector3(S * 0.5f, 1500f, -S * 0.6f), new Vector3(S * 0.5f, 0, -S * 0.3f), "08_pivots", 60);

        // the storm as a chaser sees it, at its first tornado (or 50 minutes in)
        if (storm)
        {
            storm.playing = false;
            world.PlaceStorm();
            float stormT = storm.Plan.cycles != null ? (float)storm.Plan.cycles[0].times[3] : 50f;
            storm.StepTo(stormT, 0f, true);
            Sync();
            var up = storm.UpdraftWorld(stormT);
            bool torOn = storm.TornadoAmount > 0.15f;
            var target = torOn ? storm.TornadoGroundWorld : new Vector3(up.x, 0, up.z);
            var mv = new Vector3((float)storm.Plan.motion.x, 0f, (float)storm.Plan.motion.y);
            var from = target + Quaternion.Euler(0, 100, 0) * (mv.sqrMagnitude > 0.01f ? mv.normalized : Vector3.forward) * 9000f;
            // (the real-data maps: from the nearest road, as a chaser would stand, not inside the woods)
            if (Real) from = world.routes.SelectMany(r => r.points).OrderBy(p => Flat(p - from).sqrMagnitude).First();
            from = OnGround(from, 2f);
            storm.ResetHistory(cam);
            var aim = new Vector3(target.x, from.y + 900f, target.z);
            Shot(cam, from, aim, "09_storm_chaser", 70, 16);
            rep.AppendLine($"Storm view: {storm.preset} seed {storm.seed} at {stormT:0.0} min ({storm.Frame.stage}), tornado {(torOn ? "on" : "off")}, camera {Flat(target - from).magnitude / 1609.344f:0.0} mi away.").AppendLine();
        }
        foreach (var n in new[] { "01_overview", "02_state_junction", "03_gravel_eye", "04_truck_state_route", "05_river_bridge", "06_farmstead", "07_horizon", Real ? "08_town" : "08_pivots", "09_storm_chaser" })
            rep.AppendLine($"- `Screenshots/{Prefix}_{n}.png`");
        return true;
    }

    /// <summary>The two longest differently named highways that meet (real-data maps).</summary>
    static (string, string) StateCrossing(TestMapWorld world)
    {
        var names = world.routes.Where(r => r.cls == "state").GroupBy(r => r.name).OrderByDescending(g => g.Sum(Length)).Select(g => g.Key).Take(8).ToList();
        foreach (var a in names) foreach (var b in names)
                if (string.CompareOrdinal(a, b) < 0 && Flat(Junction(world, a, b) - Junction(world, b, a)).magnitude < 15f) return (a, b);
        return (names[0], names[1]);
    }

    /// <summary>Where two routes cross (closest pair of their points, over every piece of each name).</summary>
    static Vector3 Junction(TestMapWorld world, string a, string b)
    {
        var A = world.routes.Where(r => r.name == a).SelectMany(r => r.points).ToArray(); var B = world.routes.Where(r => r.name == b).SelectMany(r => r.points).ToArray();
        float best = float.MaxValue; var at = Vector3.zero;
        foreach (var p in A) foreach (var q in B)
            {
                float d = Flat(p - q).sqrMagnitude;
                if (d < best) { best = d; at = p; }
            }
        return at;
    }
}
